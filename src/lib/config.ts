// ----------------------------------------------------------------------------
// ЗАЧЕМ ТАКОЙ ФАЙЛ НУЖЕН?
// Если раскидать `process.env.MUSIC_DIR` по десяти файлам, то:
//   * невозможно понять, какие настройки вообще есть;
//   * невозможно поменять значение по умолчанию в одном месте;
//   * легко опечататься в имени переменной и не заметить этого.
// Поэтому все «магические» пути собираются здесь и экспортируются как
// обычные константы. Дальше по коду все импортируют их отсюда.
//
// ВАЖНО: этот файл выполняется ТОЛЬКО на сервере (в Node/Bun), потому что
// использует модули `node:path`, `node:fs` и `process`. В браузере таких
// модулей нет. Поэтому импортировать config.ts можно только из серверного
// кода: Server Components, Route Handlers, скриптов. Не из "use client"!
// ============================================================================

import fs from "node:fs";
import path from "node:path";

/**
 * Превращает путь из переменной окружения в АБСОЛЮТНЫЙ путь.
 *
 * ── Почему это обязательно? ────────────────────────────────────────────────
 * Относительный путь вида "./music" означает "музыка рядом с текущей рабочей
 * папкой процесса". Но рабочая папка (process.cwd()) может отличаться:
 *   * запустил `bun run dev` из корня проекта  → cwd = /home/august/.../player
 *   * запустил через Docker                    → cwd = /app
 *   * запустил через systemd из другой папки   → cwd вообще неизвестно какой
 * Если хранить относительный путь, всё сломается при смене способа запуска.
 * Абсолютный путь такой проблемы не имеет.
 *
 * ── Что делает path.resolve? ───────────────────────────────────────────────
 * Если путь абсолютный ("/music") — возвращает его как есть.
 * Если относительный ("./music") — приклеивает к process.cwd().
 */
function absoluteFromEnv(rawValue: string | undefined, fallback: string): string {
  // Оператор `??` (nullish coalescing) возвращает правую часть, только если
  // слева null или undefined. Пустая строка "" — это НЕ null, поэтому
  // дополнительно отсекаем пустые значения через .trim().
  const value = rawValue?.trim() || fallback;
  return path.resolve(value);
}

/**
 * Корень проекта. Нужен, чтобы пути по умолчанию были предсказуемыми:
 * `bun run dev` запускается из корня, а в Docker мы зададим WORKDIR=/app.
 */
const projectRoot = process.cwd();

/**
 * Папка с музыкой. Именно её обходит сканер.
 *
 * Пример для Docker: MUSIC_DIR=/music (туда монтируется папка с хоста).
 */
export const MUSIC_DIR = absoluteFromEnv(process.env.MUSIC_DIR, path.join(projectRoot, "music"));

/**
 * Файл базы данных SQLite.
 *
 * SQLite — это ОДИН файл на диске. Не сервер, не процесс, не порт.
 * Удалил файл — потерял библиотеку (но музыка на диске останется цела,
 * поэтому её всегда можно пересканировать).
 *
 * В Docker этот путь указывает внутрь volume, чтобы база пережила
 * удаление контейнера.
 */
export const DB_PATH = absoluteFromEnv(process.env.DB_PATH, path.join(projectRoot, "data", "music.db"));

/**
 * Папка, куда сканер выкладывает обложки альбомов, вытащенные из тегов.
 *
 * ── Почему обложки не лежат в базе? ─────────────────────────────────────────
 * Можно было бы хранить картинку прямо в SQLite в колонке BLOB. Но тогда
 * каждый SELECT по таблице tracks таскает за собой сотни килобайт картинок,
 * база быстро распухает, а бэкапить её становится больно.
 * Намного быстрее держать в базе только имя файла картинки, а сам файл
 * отдавать обычным файловым стримом.
 */
export const COVERS_DIR = absoluteFromEnv(process.env.COVERS_DIR, path.join(projectRoot, "data", "covers"));

/**
 * Какие расширения сканер считает музыкой.
 *
 * `as const` превращает обычный массив строк в «кортеж литералов»:
 * вместо типа string[] получаем readonly [".mp3", ".flac", ...].
 * Это даёт TypeScript точное знание о содержимом и делает константу
 * неизменяемой.
 *
 * `.flac` — без потерь (lossless), `.m4a`/`.aac` — формат Apple,
 * `.ogg`/`.opus` — открытые форматы, `.wav` — «сырая» волна.
 */
export const AUDIO_EXTENSIONS = [".mp3", ".flac", ".m4a", ".aac", ".ogg", ".opus", ".wav"] as const;

/**
 * Порт, на котором работает сервер. Нужен только чтобы показать ссылку
 * в консоли и в Docker.
 */
export const PORT = Number(process.env.PORT ?? 3000);

// ---------------------------------------------------------------------------
// Создание рабочих папок при старте.
// ---------------------------------------------------------------------------
// `mkdirSync` с флагом `recursive: true` работает как `mkdir -p`: создаёт всю
// цепочку папок, а если папка уже есть — молча ничего не делает (ошибки нет).
//
// Мы делаем это при импорте модуля, чтобы первый же запрос к базе или
// сохранение обложки не упали с ошибкой "no such file or directory".
//
// try/catch нужен потому, что папка может быть доступна только для чтения
// (например, в Docker music смонтирован как read-only — это нормально).
// ---------------------------------------------------------------------------
export function ensureRuntimeDirs(): void {
  for (const dir of [path.dirname(DB_PATH), COVERS_DIR]) {
    try {
      fs.mkdirSync(dir, { recursive: true });
    } catch (error) {
      // Не валим приложение целиком: возможно, папка уже есть и просто
      // недоступна на запись. Ошибка всё равно всплывёт при первой записи.
      console.warn(`[config] не удалось создать папку ${dir}:`, error);
    }
  }
}

// Выполняем сразу при загрузке модуля.
ensureRuntimeDirs();

// ===========================================================================
// ПУТИ К ФАЙЛАМ: ОТНОСИТЕЛЬНЫЕ, А НЕ АБСОЛЮТНЫЕ.
// ---------------------------------------------------------------------------
// ── ИСТОРИЯ ОДНОЙ ОШИБКИ, КОТОРАЯ ЛОМАЛА ВОСПРОИЗВЕДЕНИЕ ────────────────────
// Сначала в колонке tracks.path хранился АБСОЛЮТНЫЙ путь к файлу:
//
//     локальный запуск:  /home/august/projects_all/.../music/ATL - Ящик.mp3
//     запуск в Docker:   /music/ATL - Ящик.mp3
//
// Выглядит безобидно, но база-то ОДНА и та же — она лежит в томе ./data,
// который монтируется и в Docker, и используется локально. Значит:
//
//     1. просканировал локально  → в базе пути /home/august/...
//     2. запустил через Docker   → таких путей внутри контейнера НЕТ
//     3. открываешь плеер        → 404 на /api/tracks/N/stream
//        («Файл не найден на диске»)
//
// Именно так и случилось в этом проекте: тестовый запуск через
// `docker compose up` записал в общую базу пути контейнера, и после этого
// локально музыка перестала играть.
//
// ── КАК ПРАВИЛЬНО ──────────────────────────────────────────────────────────
// Файловую систему можно монтировать куда угодно — изменится только
// местоположение. А вот путь ВНУТРИ библиотеки остаётся неизменным:
//
//     "ATL - Ящик.mp3"
//     "ATL/Ящик/01 - Трек.mp3"
//
// Поэтому в базе храним именно ОТНОСИТЕЛЬНЫЙ путь, а абсолютный собираем
// в момент обращения, добавляя MUSIC_DIR.
//
// Что это даёт:
//   * одна и та же база работает и локально, и в Docker, и на другом
//     компьютере — если папка с музыкой примонтирована, всё найдётся;
//   * том ./data действительно становится переносимым;
//   * база перестаёт «привязываться» к конкретной машине.
//
// Общий принцип: **храни то, что не меняется при переносе**.
// ===========================================================================

/**
 * Абсолютный путь файла → путь относительно корня музыкальной библиотеки.
 *
 * Примеры (при MUSIC_DIR = "/music"):
 *     /music/ATL - Ящик.mp3                  → "ATL - Ящик.mp3"
 *     /music/ATL/Ящик/01.mp3                 → "ATL/Ящик/01.mp3"
 *     /другой/путь/файл.mp3                  → null (файл вне библиотеки)
 */
export function toMusicRelative(absolutePath: string): string | null {
  // path.relative даёт путь ОТ корня К файлу. Если файл вне библиотеки,
  // результат начнётся с ".." — такие отбрасываем.
  const relative = path.relative(MUSIC_DIR, absolutePath);
  if (relative === "" || relative.startsWith("..") || path.isAbsolute(relative)) return null;
  return relative;
}

/**
 * Относительный путь из базы → абсолютный путь в файловой системе.
 * Именно эту дорогу проходит каждый запрос на воспроизведение файла.
 */
export function resolveMusicPath(relativePath: string): string {
  return path.join(MUSIC_DIR, relativePath);
}

/**
 * Небольшая утилита для логов сервера. Префикс помогает отличать наши
 * сообщения от шума Next.js.
 */
export function log(message: string, ...details: unknown[]): void {
  console.log(`[player] ${message}`, ...details);
}
