// ============================================================================
// src/lib/db/client.ts — ПОДКЛЮЧЕНИЕ К SQLITE (одно на всё приложение).
// ----------------------------------------------------------------------------
// Этот файл отвечает за три вещи:
//   1. Открыть файл базы данных.
//   2. Настроить соединение (PRAGMA-параметры).
//   3. Применить миграции, чтобы таблицы точно существовали.
//
// Дальше весь остальной код просто пишет `import { db } from "@/lib/db/client"`
// и работает с базой.
// ============================================================================

import { Database } from "bun:sqlite";
import { drizzle, type BunSQLiteDatabase } from "drizzle-orm/bun-sqlite";
import { migrate } from "drizzle-orm/bun-sqlite/migrator";
import path from "node:path";

import { DB_PATH, log } from "@/lib/config";
import * as schema from "@/lib/db/schema";

// ============================================================================
// ЧТО ТАКОЕ drizzle(db) И ЗАЧЕМ ОН НУЖЕН
// ----------------------------------------------------------------------------
// `bun:sqlite` — низкоуровневый драйвер. Он умеет выполнять SQL-строки:
//     const db = new Database("music.db");
//     db.query("SELECT * FROM tracks WHERE artist = ?").all("ATL");
// Но он ничего не знает про TypeScript: вернёт `any[]`, и опечатку в имени
// колонки ты увидишь только в момент выполнения.
//
// `drizzle(nativeDb, { schema })` — это ОБЁРТКА над драйвером, которая
// добавляет типы и удобный конструктор запросов:
//     db.select().from(tracks).where(eq(tracks.artist, "ATL"))
// Результат сразу имеет тип TrackRow[], а `tracks.artistt` редактор
// подчеркнёт как ошибку ещё до запуска.
//
// При этом под капотом всё равно выполняется обычный SQL. Магии нет.
// ============================================================================

/**
 * Тип нашей базы. Вынесен отдельно, чтобы функции в queries.ts могли
 * принимать базу как аргумент — это сильно упрощает тестирование
 * (можно подсунуть базу в памяти вместо файла).
 */
export type AppDatabase = BunSQLiteDatabase<typeof schema>;

// ============================================================================
// ПОЧЕМУ БАЗА ХРАНИТСЯ В globalThis, А НЕ В ОБЫЧНОЙ ПЕРЕМЕННОЙ
// ----------------------------------------------------------------------------
// В режиме разработки (`next dev`) Next.js перезагружает изменившиеся модули
// «на горячую» (Hot Module Replacement). При этом файл client.ts может быть
// выполнен заново — и тогда мы откроем ВТОРОЕ соединение с той же базой.
// А через сотню правок — сотое соединение. Это утечка ресурсов и странные
// ошибки вида "database is locked".
//
// globalThis — глобальный объект процесса. Он живёт всё время работы сервера
// и НЕ сбрасывается при перезагрузке модулей. Поэтому мы держим базу в нём:
//     нет в globalThis → создать и положить
//     есть в globalThis → переиспользовать
//
// В production-сборке этот трюк безвреден: модуль и так выполняется один раз.
// ============================================================================

/** Ключ, под которым соединение лежит в globalThis. */
const GLOBAL_KEY = "__personalMusicPlayerDb__";

/**
 * Описываем форму глобального объекта.
 * TypeScript не знает, что мы «подкладываем» туда свои поля, поэтому
 * расширяем тип globalThis через declare global.
 */
declare global {
  var __personalMusicPlayerDb__: { db: AppDatabase; raw: Database } | undefined;
}

/**
 * Открывает и настраивает соединение с SQLite.
 *
 * Функция вызывается ОДИН раз за жизнь процесса (см. singleton ниже).
 */
function createDatabase(): { db: AppDatabase; raw: Database } {
  // --------------------------------------------------------------------------
  // new Database(путь) — открывает файл базы. Если файла нет, SQLite создаст
  // его при первой записи. Это одна из причин, почему SQLite так удобен:
  // никакого «подними сервер БД, создай пользователя, выдай права».
  // --------------------------------------------------------------------------
  const raw = new Database(DB_PATH, { create: true });

  // --------------------------------------------------------------------------
  // PRAGMA — это команды настройки самого SQLite (аналоги SET в других СУБД).
  // Их принято выполнять сразу после открытия соединения.
  //
  // ── PRAGMA journal_mode = WAL ─────────────────────────────────────────────
  // WAL = Write-Ahead Logging («журнал упреждающей записи»).
  // В обычном режиме (DELETE) при записи база блокируется целиком: читатели
  // ждут, пока писатель закончит. В режиме WAL изменения пишутся в отдельный
  // файл-журнал, а читатели продолжают читать старую версию страниц.
  // Результат: можно одновременно читать список треков и писать историю
  // прослушиваний. Для веб-приложения это критично.
  //
  // ── PRAGMA foreign_keys = ON ──────────────────────────────────────────────
  // По умолчанию SQLite НЕ проверяет внешние ключи (историческая особенность
  // ради совместимости). Включаем явно, иначе ON DELETE CASCADE не сработает
  // и удаление плейлиста оставит мусор в playlist_tracks.
  //
  // ── PRAGMA busy_timeout = 5000 ────────────────────────────────────────────
  // Если база всё-таки занята другой операцией, ждать её освобождения до 5
  // секунд вместо мгновенной ошибки "SQLITE_BUSY".
  //
  // ── PRAGMA synchronous = NORMAL ───────────────────────────────────────────
  // В режиме WAL это безопасный компромисс: данные не потеряются при падении
  // приложения, но запись идёт заметно быстрее, чем при FULL.
  // --------------------------------------------------------------------------
  raw.exec("PRAGMA journal_mode = WAL;");
  raw.exec("PRAGMA foreign_keys = ON;");
  raw.exec("PRAGMA busy_timeout = 5000;");
  raw.exec("PRAGMA synchronous = NORMAL;");

  // --------------------------------------------------------------------------
  // Оборачиваем «сырое» соединение в Drizzle и передаём схему.
  //
  // Аргумент `schema` нужен для двух вещей:
  //   * чтобы работал реляционный API `db.query.tracks.findMany({ with: ... })`;
  //   * чтобы Drizzle знал обо всех таблицах разом.
  // --------------------------------------------------------------------------
  const db = drizzle(raw, { schema });

  // --------------------------------------------------------------------------
  // МИГРАЦИИ.
  //
  // migrate() читает папку ./drizzle, находит в ней SQL-файлы и применяет те,
  // которые ещё не применялись (факт применения записан во внутреннюю
  // таблицу __drizzle_migrations).
  //
  // Смысл миграций: структура базы меняется вместе с кодом. Добавил колонку
  // в schema.ts → запустил `bunx drizzle-kit generate` → появился новый
  // SQL-файл. На другой машине (или в Docker) тот же самый файл применится
  // автоматически при старте, и база будет ровно такой же.
  //
  // migrationsFolder указываем абсолютным путём, потому что рабочая папка
  // в Docker (/app) может отличаться от локальной.
  // --------------------------------------------------------------------------
  migrate(db, { migrationsFolder: path.resolve(process.cwd(), "drizzle") });

  log(`SQLite открыта: ${DB_PATH}`);

  return { db, raw };
}

// ============================================================================
// ЛЕНИВАЯ ИНИЦИАЛИЗАЦИЯ (lazy initialization)
// ----------------------------------------------------------------------------
// Мы НЕ открываем базу на верхнем уровне модуля, а делаем это внутри функции
// getDatabase(). Причина: при `next build` серверные модули могут быть
// импортированы во время сборки. Если бы база открывалась при импорте, сборка
// пыталась бы создать файл базы — а это побочный эффект, которого на этапе
// сборки быть не должно.
//
// Схема простая: первый вызов getDatabase() создаёт соединение, все
// последующие получают уже готовое.
// ============================================================================
function getDatabase(): { db: AppDatabase; raw: Database } {
  // Читаем кэш из глобального объекта.
  const cached = globalThis[GLOBAL_KEY];
  if (cached) return cached;

  const created = createDatabase();
  globalThis[GLOBAL_KEY] = created;
  return created;
}

/**
 * ГЛАВНЫЙ ЭКСПОРТ ФАЙЛА.
 *
 * Это не сама база, а Proxy — «умная прослойка», которая притворяется базой.
 *
 * ── Зачем так сложно? ──────────────────────────────────────────────────────
 * Хочется писать просто `db.select().from(tracks)`, а не
 * `getDatabase().db.select().from(tracks)` в каждой функции. Но если написать
 * `export const db = getDatabase().db`, то соединение откроется в момент
 * импорта — а нам это как раз и не нужно (см. объяснение выше).
 *
 * Proxy решает проблему: он создаётся мгновенно и «пустой», а настоящую базу
 * открывает только тогда, когда к нему впервые обращаются за свойством.
 * Для внешнего кода выглядит как обычная база данных.
 * ============================================================================
 */
export const db: AppDatabase = new Proxy({} as AppDatabase, {
  get(_target, property, receiver) {
    // При первом обращении лениво создаём (или достаём из кэша) соединение.
    const { db: realDb } = getDatabase();
    // Проксируем чтение свойства в настоящую базу.
    // Reflect.get сохраняет корректный контекст `this` внутри методов Drizzle.
    return Reflect.get(realDb, property, receiver);
  },
});

/**
 * Доступ к «сырому» драйверу bun:sqlite.
 * Нужен в редких случаях, когда требуется выполнить SQL, который Drizzle
 * не умеет строить, например массовые PRAGMA или ANALYZE.
 */
export function getRawDatabase(): Database {
  return getDatabase().raw;
}

/**
 * Переэкспорт схемы. Удобно: в других файлах достаточно импортировать
 * что-то одно.
 */
export { schema };
