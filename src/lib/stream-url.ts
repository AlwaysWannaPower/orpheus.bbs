// src/lib/stream-url.ts — АДРЕСА АУДИО И ОБЛОЖЕК.
// ----------------------------------------------------------------------------
// URL аудиопотока собирается в одном месте: если однажды поменяется путь
// или способ передачи токена — править придётся только здесь.
//
// ── ИСТОРИЯ ОДНОГО ПОДВОДНОГО КАМНЯ (важно прочитать) ─────────────────────
// Сначала токен брался из переменной окружения прямо здесь:
//
//     const STREAM_TOKEN = process.env.NEXT_PUBLIC_STREAM_TOKEN ?? "";
//
// Выглядело логично, но ломалось в самом важном сценарии — запуске
// через Docker.
//
// ── ПОЧЕМУ ЭТО НЕ РАБОТАЛО ────────────────────────────────────────────────
// Переменные с префиксом NEXT_PUBLIC_ подставляются в код НЕ В МОМЕНТ
// ЗАПУСКА, А В МОМЕНТ СБОРКИ. Сборка в Docker выполняется на этапе
// `docker compose build`, а переменные из блока `environment:` применяются
// позже — при `docker compose up`. То есть во время сборки токена ещё нет,
// и в бандл уезжает пустая строка.
//
// Проверить это можно так:
//     grep -rl 'NEXT_PUBLIC_STREAM_TOKEN' .next/static
// Если значение не было задано при сборке — в файле останется не строка,
// а обращение вида `env.NEXT_PUBLIC_STREAM_TOKEN`, которое в браузере
// вернёт undefined.
//
// ── КАК СДЕЛАНО ТЕПЕРЬ ────────────────────────────────────────────────────
// Токен читает СЕРВЕР в момент запроса (в src/app/layout.tsx), и передаёт
// его в клиентские компоненты обычным пропсом. Никаких сборок-загадок:
// значение берётся из окружения контейнера, когда контейнер уже запущен.
//
// Что это даёт:
//   * работает и локально, и в Docker, и с docker compose без build-args;
//   * токен по-прежнему не секрет от браузера (он и так был бы виден
//     в запросах), но теперь он не «запекается» в образ;
//   * один и тот же образ можно запускать с разными токенами.
//
// Правило на будущее: **NEXT_PUBLIC_* подходит только для значений,
// известных во время сборки** (например, название сайта). Всё, что должно
// настраиваться при запуске, передавай с сервера пропсом или через cookie.
// ============================================================================

/**
 * Возвращает URL аудиопотока для трека.
 *
 * @param trackId идентификатор трека в базе
 * @param token   необязательный токен доступа. Пустая строка или undefined
 *                означают, что проверка доступа выключена (см.
 *                src/app/api/tracks/[id]/stream/route.ts).
 */
export function buildStreamUrl(trackId: number, token?: string): string {
  const base = `/api/tracks/${trackId}/stream`;

  if (!token) return base;

  // encodeURIComponent нужен, если в токене окажутся символы вроде & или #,
  // которые в URL имеют специальный смысл и сломали бы адрес.
  return `${base}?token=${encodeURIComponent(token)}`;
}

/** URL обложки трека. Обложки токеном не защищаются. */
export function buildCoverUrl(trackId: number): string {
  return `/api/tracks/${trackId}/cover`;
}
