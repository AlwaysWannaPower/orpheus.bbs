// ----------------------------------------------------------------------------
// ── ЧТО ТАКОЕ ЛИНТЕР ──────────────────────────────────────────────────────
// Линтер — программа, которая читает код, НЕ запуская его, и ищет проблемы:
//   * настоящие ошибки (переменная не объявлена, недостижимый код);
//   * подозрительные места (забыл await, неиспользуемая переменная);
//   * нарушения стиля и хороших практик React/Next.js.
//
// Это «второй компилятор»: TypeScript проверяет типы, ESLint — всё остальное.
//
// ── ЧТО ТАКОЕ FLAT CONFIG ─────────────────────────────────────────────────
// Начиная с ESLint 9 настройка — это обычный JavaScript-файл, который
// экспортирует МАССИВ конфигураций. Старый формат (.eslintrc) использовал
// отдельные файлы и «магические» правила наследования — от него отказались.
//
// Порядок в массиве важен: правила применяются сверху вниз, и последняя
// подходящая конфигурация побеждает.
// ============================================================================

import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";

const eslintConfig = defineConfig([
  // --------------------------------------------------------------------------
  // 1. ГОТОВЫЕ НАБОРЫ ПРАВИЛ ОТ NEXT.JS.
  //
  //   core-web-vitals  — правила по производительности и доступности
  //                      (например, использование <Image> и <Link>);
  //   typescript       — правила для TypeScript-кода.
  //
  // Оператор `...` (spread) «раскрывает» массивы конфигураций внутрь
  // нашего массива — иначе получился бы массив из двух массивов.
  // --------------------------------------------------------------------------
  ...nextVitals,
  ...nextTs,

  // --------------------------------------------------------------------------
  // 2. ЧТО НЕ ПРОВЕРЯТЬ.
  //
  // globalIgnores — список путей, которые ESLint пропускает целиком.
  // Здесь важны две вещи:
  //
  //   * каталоги со сгенерированным и скачанным кодом проверять бессмысленно:
  //     мы всё равно не будем править эти файлы, а проверка занимает время
  //     и выдаёт сотни «ошибок» в чужом коде;
  //
  //   * ESLint по умолчанию НЕ игнорирует node_modules, но игнорирует
  //     папки, начинающиеся с точки... а вот вложенные кэши внутри проекта
  //     (например, .bun-install) надо перечислить явно.
  // --------------------------------------------------------------------------
  globalIgnores([
    // Сгенерированное Next.js.
    ".next/**",
    "out/**",
    "build/**",
    "next-env.d.ts",

    // Зависимости.
    "node_modules/**",

    // Локальный кэш пакетов Bun — появляется, если системный ~/.bun
    // недоступен для записи (см. AGENTS.md, раздел «Особенности окружения»).
    // Внутри лежат СОТНИ чужих .d.ts-файлов: линтовать их бессмысленно.
    ".bun-install/**",
    ".bun-tmp/**",

    // Данные приложения и музыка — не код.
    "data/**",
    "music/**",

    // Миграции сгенерированы автоматически — править их руками нельзя,
    // значит и проверять нечего.
    "drizzle/meta/**",
  ]),
]);

export default eslintConfig;
