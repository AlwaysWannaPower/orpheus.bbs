// ============================================================================
// src/lib/scanner/walk.ts — ОБХОД ПАПОК В ПОИСКАХ МУЗЫКИ.
// ----------------------------------------------------------------------------
// Задача: получив папку /music, найти в ней (и во всех вложенных папках)
// все файлы, которые похожи на музыку, и вернуть их список с информацией
// о размере и времени изменения.
//
// Это классическая рекурсивная задача: «пройти по дереву каталогов».
// ============================================================================

import fs from "node:fs/promises";
import path from "node:path";

import { AUDIO_EXTENSIONS } from "@/lib/config";

/**
 * Описание одного найденного файла.
 * Обрати внимание: мы собираем ровно то, что нужно сканеру, и ничего лишнего.
 */
export type FoundFile = {
  /** Абсолютный путь к файлу на диске. */
  absolutePath: string;
  /** Только имя файла, например "ATL - Ящик.mp3". */
  filename: string;
  /** Размер в байтах. */
  size: number;
  /** Время последнего изменения файла (Date). */
  mtime: Date;
};

/**
 * Проверяет, похоже ли имя файла на музыку.
 *
 * ── ЧТО ЗДЕСЬ ПРОИСХОДИТ ──────────────────────────────────────────────────
 * 1. path.extname("song.MP3") вернёт ".MP3" — с точкой и в том регистре,
 *    в каком он записан в файле. Поэтому приводим к нижнему регистру.
 * 2. AUDIO_EXTENSIONS объявлен через `as const`, поэтому его тип —
 *    readonly [".mp3", ".flac", ...], а не string[]. Массив `includes`
 *    у такого типа ждёт строго один из этих литералов, а у нас обычная
 *    строка string — TypeScript справедливо ругается.
 *    Приведение `as readonly string[]` снимает излишнюю строгость.
 */
function isAudioFile(filename: string): boolean {
  const extension = path.extname(filename).toLowerCase();
  return (AUDIO_EXTENSIONS as readonly string[]).includes(extension);
}

/**
 * Служебная функция: нужно ли вообще заходить в эту папку.
 *
 * Пропускаем:
 *   * скрытые папки (начинаются с точки) — там обычно .git, .cache и прочий
 *     служебный мусор, в котором музыки не бывает;
 *   * папки вида "@eaDir" и "#recycle" — их создают NAS-устройства Synology,
 *     и внутри лежат копии тех же файлов.
 */
function isSkippableDirectory(name: string): boolean {
  return name.startsWith(".") || name === "@eaDir" || name === "#recycle";
}

/**
 * Рекурсивно обходит папку и собирает все аудиофайлы.
 *
 * ── ЧТО ТАКОЕ РЕКУРСИЯ ────────────────────────────────────────────────────
 * Функция вызывает саму себя для каждой вложенной папки. Обязательно нужна
 * «точка остановки» (у нас — когда папок больше нет), иначе будет
 * бесконечный цикл.
 *
 * ── ПОЧЕМУ async/await ────────────────────────────────────────────────────
 * Чтение диска — операция ввода-вывода (I/O). Она физически медленная
 * по сравнению с работой процессора. `await` позволяет процессу заниматься
 * другими делами, пока диск отвечает, вместо того чтобы тупо ждать.
 *
 * ── ПРО ПАРАЛЛЕЛЬНОСТЬ ────────────────────────────────────────────────────
 * Здесь сознательно СЕРИЙНЫЙ обход: просто, предсказуемо и достаточно быстро
 * для папки с музыкой. Если однажды понадобится ускорить — можно обходить
 * подпапки через Promise.all, но тогда легко упереться в лимит открытых
 * файловых дескрипторов.
 */
export async function walkMusicDirectory(
  rootDir: string,
  options: { onFound?: (count: number) => void } = {},
): Promise<FoundFile[]> {
  const result: FoundFile[] = [];

  /**
   * Внутренняя (локальная) функция. Она видит `result` из внешней области
   * видимости — это называется ЗАМЫКАНИЕ (closure): функция «запоминает»
   * переменные, в которых была создана.
   */
  async function walk(currentDir: string): Promise<void> {
    let entries;

    try {
      // ----------------------------------------------------------------------
      // readdir с withFileTypes: true возвращает не просто имена, а объекты
      // Dirent, у которых есть методы isDirectory() / isFile() / isSymbolicLink().
      //
      // Это ВАЖНО для производительности: тип записи уже известен из ответа
      // файловой системы, и нам не надо делать отдельный stat() на каждый файл.
      // ----------------------------------------------------------------------
      entries = await fs.readdir(currentDir, { withFileTypes: true });
    } catch (error) {
      // Папка может исчезнуть между обходом и чтением, или не быть прав.
      // Не роняем весь скан из-за одной проблемной папки — идём дальше.
      console.warn(`[scanner] не удалось прочитать папку ${currentDir}:`, error);
      return;
    }

    for (const entry of entries) {
      const fullPath = path.join(currentDir, entry.name);

      // ----------------------------------------------------------------------
      // Символические ссылки пропускаем.
      //
      // Симлинк — это «ярлык» на другой файл или папку. Если по нему пойти,
      // можно попасть в бесконечный цикл (папка ссылается сама на себя)
      // или случайно выйти за пределы музыкальной папки и просканировать
      // пол-диска. Для домашнего плеера это лишний риск.
      // ----------------------------------------------------------------------
      if (entry.isSymbolicLink()) continue;

      if (entry.isDirectory()) {
        if (isSkippableDirectory(entry.name)) continue;
        // Рекурсивный вызов — вот она, рекурсия.
        await walk(fullPath);
        continue;
      }

      if (!entry.isFile()) continue;
      if (!isAudioFile(entry.name)) continue;

      try {
        // ------------------------------------------------------------------
        // stat даёт размер, время изменения и прочие метаданные файла.
        // Нам нужны size и mtime — по ним сканер поймёт, изменился ли файл.
        // ------------------------------------------------------------------
        const stats = await fs.stat(fullPath);
        result.push({
          absolutePath: fullPath,
          filename: entry.name,
          size: stats.size,
          mtime: stats.mtime,
        });

        // Сообщаем наружу прогресс (интерфейс может показать «найдено 123»).
        options.onFound?.(result.length);
      } catch (error) {
        console.warn(`[scanner] не удалось получить информацию о ${fullPath}:`, error);
      }
    }
  }

  await walk(rootDir);
  return result;
}

/**
 * Проверяет, что папка с музыкой существует и доступна.
 * Возвращает человекочитаемое описание проблемы — его удобно показать в UI.
 */
export async function checkMusicDirectory(dir: string): Promise<{ ok: boolean; message: string }> {
  try {
    const stats = await fs.stat(dir);
    if (!stats.isDirectory()) {
      return { ok: false, message: `${dir} — это не папка` };
    }
    return { ok: true, message: dir };
  } catch {
    return {
      ok: false,
      message: `Папка с музыкой не найдена: ${dir}. Проверь переменную MUSIC_DIR в .env`,
    };
  }
}
