// ============================================================================
// src/lib/search-url.test.ts — ТЕСТЫ ДЛЯ ЛОГИКИ ПОИСКА.
// ----------------------------------------------------------------------------
// ── ЗАЧЕМ ЭТИ ТЕСТЫ ───────────────────────────────────────────────────────
// В проекте был реальный баг: страница библиотеки запрашивалась у сервера
// БЕСКОНЕЧНО, примерно раз в секунду. Причина — эффект в SearchBar менял
// значение, от которого сам же зависел.
//
// Один из тестов ниже (он называется «идемпотентность») проверяет ровно то
// свойство, отсутствие которого и вызывало цикл:
//
//     применил функцию к адресу → получил новый адрес
//     применил её к новому адресу ЕЩЁ РАЗ → должно получиться null
//     (то есть «менять больше нечего»)
//
// Если однажды кто-то перепишет функцию и сломает это свойство — тест
// упадёт ДО того, как баг доберётся до сервера.
//
// ── КАК ЗАПУСКАТЬ ─────────────────────────────────────────────────────────
//     bun test
//
// Bun умеет запускать тесты без установки чего-либо: `describe`, `test`,
// `expect` встроены в рантайм. Это одна из причин, почему проект лёгкий —
// отдельный фреймворк для тестов не нужен.
// ============================================================================

import { describe, expect, test } from "bun:test";

import { buildSearchUrl } from "@/lib/search-url";

/** Мелочь для читаемости: превращаем строку запроса в объект URLSearchParams. */
function params(query: string): URLSearchParams {
  return new URLSearchParams(query);
}

describe("buildSearchUrl", () => {
  // ------------------------------------------------------------------------
  // ГЛАВНЫЙ ТЕСТ. Именно его отсутствие позволяло серверу молотить вхолостую.
  // ------------------------------------------------------------------------
  describe("идемпотентность — защита от бесконечного цикла", () => {
    test("второй вызов с уже применённым адресом не даёт нового адреса", () => {
      // Пользователь ввёл «ящик» на странице без параметров.
      const first = buildSearchUrl(params(""), "/", "ящик");

      // Первый вызов обязан что-то изменить.
      expect(first).toBe("/?search=%D1%8F%D1%89%D0%B8%D0%BA");

      // Разбираем получившийся адрес обратно — как это сделал бы роутер.
      const afterNavigation = params(first!.split("?")[1] ?? "");
      const second = buildSearchUrl(afterNavigation, "/", "ящик");

      // Второй вызов менять нечего → null → запроса на сервер НЕ будет.
      // Раньше здесь возвращался тот же адрес, и цикл не останавливался.
      expect(second).toBeNull();
    });

    test("повторное применение с пустым вводом тоже ничего не меняет", () => {
      const first = buildSearchUrl(params("search=атл"), "/", "");
      expect(first).toBe("/");

      const second = buildSearchUrl(params(""), "/", "");
      expect(second).toBeNull();
    });
  });

  // ------------------------------------------------------------------------
  describe("обычные случаи", () => {
    test("добавляет параметр поиска", () => {
      expect(buildSearchUrl(params(""), "/", "atl")).toBe("/?search=atl");
    });

    test("убирает параметр при пустом вводе", () => {
      expect(buildSearchUrl(params("search=atl"), "/", "")).toBe("/");
    });

    test("обрезает пробелы по краям", () => {
      // «  атл  » и «атл» должны считаться одним и тем же запросом,
      // иначе пользователь получит два разных адреса для одного поиска.
      expect(buildSearchUrl(params(""), "/", "  atl  ")).toBe("/?search=atl");
    });

    test("ввод из одних пробелов считается пустым", () => {
      expect(buildSearchUrl(params("search=atl"), "/", "   ")).toBe("/");
    });
  });

  // ------------------------------------------------------------------------
  describe("сохранение прочих параметров", () => {
    test("не теряет сортировку", () => {
      const url = buildSearchUrl(params("sort=title_asc"), "/", "atl");
      expect(url).toContain("sort=title_asc");
      expect(url).toContain("search=atl");
    });

    test("не теряет фильтр избранного", () => {
      const url = buildSearchUrl(params("favorites=true&sort=album_asc"), "/", "horus");
      expect(url).toContain("favorites=true");
      expect(url).toContain("sort=album_asc");
      expect(url).toContain("search=horus");
    });

    test("при очистке поиска остальные параметры остаются на месте", () => {
      const url = buildSearchUrl(params("search=atl&sort=title_asc"), "/", "");
      expect(url).toBe("/?sort=title_asc");
    });
  });

  // ------------------------------------------------------------------------
  describe("кириллица", () => {
    test("корректно кодирует русский текст в адресе", () => {
      const url = buildSearchUrl(params(""), "/", "ящик");
      // В адресе кириллица обязана быть процентно закодирована — иначе
      // разные браузеры и серверы начнут понимать её по-разному.
      expect(url).toBe("/?search=%D1%8F%D1%89%D0%B8%D0%BA");
    });

    test("распознаёт уже закодированный русский текст и не дублирует параметр", () => {
      // Роутер отдаёт параметры уже раскодированными, поэтому сравнивать
      // надо с «ящик», а не с «%D1%8F...».
      const url = buildSearchUrl(params("search=%D1%8F%D1%89%D0%B8%D0%BA"), "/", "ящик");
      expect(url).toBeNull();
    });
  });

  // ------------------------------------------------------------------------
  describe("работа с другими страницами", () => {
    test("сохраняет путь страницы, а не только корень", () => {
      expect(buildSearchUrl(params(""), "/playlists/3", "atl")).toBe("/playlists/3?search=atl");
    });

    test("добавляет параметр к странице, где другие параметры уже есть", () => {
      expect(buildSearchUrl(params("sort=title_asc"), "/playlists/3", "atl")).toBe(
        "/playlists/3?sort=title_asc&search=atl",
      );
    });
  });
});
