// ============================================================================
// src/app/layout.tsx — КОРНЕВОЙ МАКЕТ ВСЕГО ПРИЛОЖЕНИЯ.
// ----------------------------------------------------------------------------
// ── ЧТО ТАКОЕ LAYOUT ──────────────────────────────────────────────────────
// layout.tsx — это «рамка», которая оборачивает страницы. Он НЕ
// пересоздаётся при переходах между страницами: React сохраняет его
// состояние и DOM-узлы.
//
// Именно поэтому <PlayerProvider> живёт здесь: аудиоэлемент создаётся один
// раз при открытии сайта и продолжает играть, пока пользователь листает
// библиотеку, плейлисты и историю. Если бы провайдер стоял в page.tsx,
// музыка обрывалась бы при каждом переходе.
//
// ── СТРУКТУРА ─────────────────────────────────────────────────────────────
//   <html data-theme="...">          ← сюда подставляется тема из cookie
//     <body>
//       <PlayerProvider>             ← клиентский: плеер и <audio>
//         <AppHeader />              ← серверный: читает статистику из базы
//         <div flex>
//           <Sidebar />              ← серверный: читает плейлисты
//           <main>{children}</main>  ← сюда подставляется страница
//         </div>
//         <PlayerBar />              ← клиентский: панель управления внизу
//       </PlayerProvider>
//     </body>
//   </html>
// ============================================================================

