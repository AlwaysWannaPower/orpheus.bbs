// ----------------------------------------------------------------------------
// ── ЗАДАЧА ────────────────────────────────────────────────────────────────
// Надо обработать 500 mp3-файлов. Каждый — это асинхронная операция
// (чтение с диска + разбор тегов).
//
// Вариант «по одному в цикле»:                 медленно, диск простаивает.
// Вариант «все 500 через Promise.all сразу»:   быстро, но мы откроем 500
//                                              файлов одновременно и упрёмся
//                                              в лимит файловых дескрипторов
//                                              (EMFILE: too many open files),
//                                              плюс съедим всю память.
//
// Правильный ответ — «пул воркеров»: запускаем N задач одновременно, и как
// только одна закончилась — сразу берём следующую. N обычно 4–16.
//
// Именно так работают пулы соединений с базой, пулы потоков и очереди задач.
// ============================================================================

/**
 * Применяет асинхронную функцию к каждому элементу массива, но не более
 * `limit` задач одновременно.
 *
 * ── РАЗБОР СИГНАТУРЫ ──────────────────────────────────────────────────────
 * <TItem, TResult>  — дженерики (обобщения). Функция не знает заранее,
 *                     с какими типами её вызовут. Она говорит: «дай мне
 *                     массив элементов типа TItem и функцию, превращающую
 *                     TItem в TResult, и я верну TResult[]». TypeScript
 *                     подставит конкретные типы в момент вызова.
 *
 * items: readonly TItem[]           — входной массив. readonly означает, что
 *                                     мы обещаем его не менять.
 * worker: (item, index) => Promise<TResult> — обработчик одного элемента.
 * limit: number                     — сколько задач параллельно.
 *
 * Возвращает Promise<TResult[]> — результаты В ТОМ ЖЕ ПОРЯДКЕ, что и вход.
 */
export async function mapWithConcurrency<TItem, TResult>(
  items: readonly TItem[],
  worker: (item: TItem, index: number) => Promise<TResult>,
  limit = 6,
): Promise<TResult[]> {
  // --------------------------------------------------------------------------
  // results — массив «на вырост». Заполняем его по индексам, а не push'ем,
  // чтобы порядок результатов совпадал с порядком входных элементов, даже
  // если задачи завершаются вразнобой.
  // --------------------------------------------------------------------------
  const results: TResult[] = new Array(items.length);

  // Указатель на следующий необработанный элемент.
  // ВАЖНО: это обычная переменная, а не копия для каждого воркера, поэтому
  // все воркеры «разбирают» общий список и никогда не берут один элемент дважды.
  let nextIndex = 0;

  /**
   * Один воркер: в цикле берёт следующий элемент, пока они не кончились.
   * Это и есть секрет пула — не «раздай по одному каждой задаче», а
   * «каждый сам берёт следующую задачу, когда освободился».
   */
  async function runWorker(): Promise<void> {
    while (true) {
      // Читаем и СРАЗУ увеличиваем индекс. Это безопасно, потому что
      // JavaScript однопоточный: между чтением и записью нет `await`,
      // значит другой воркер не успеет вклиниться.
      const currentIndex = nextIndex;
      nextIndex += 1;

      // Элементы кончились — воркер завершает работу.
      if (currentIndex >= items.length) return;

      try {
        results[currentIndex] = await worker(items[currentIndex], currentIndex);
      } catch (error) {
        // Ошибка одного элемента не должна валить всю пачку.
        // Пишем в лог и кладём null — вызывающий код сам решит, что делать.
        console.warn(`[async-pool] ошибка на элементе ${currentIndex}:`, error);
        results[currentIndex] = undefined as unknown as TResult;
      }
    }
  }

  // --------------------------------------------------------------------------
  // Запускаем `limit` воркеров и ждём их все.
  // Array.from({ length: n }) создаёт массив из n элементов — просто чтобы
  // было по чему «размножить» вызовы. Значения элементов нам не нужны,
  // поэтому используем подчёркивание как имя параметра (намёк: «не используется»).
  // --------------------------------------------------------------------------
  const workerCount = Math.max(1, Math.min(limit, items.length));
  const workers = Array.from({ length: workerCount }, () => runWorker());

  await Promise.all(workers);
  return results;
}
