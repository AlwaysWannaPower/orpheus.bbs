"use client";

// ============================================================================
// src/app/error.tsx — ГРАНИЦА ОШИБОК (ERROR BOUNDARY).
// ----------------------------------------------------------------------------
// Если серверный компонент или клиентский код выбросит исключение,
// Next.js покажет этот файл вместо «белого экрана смерти».
//
// ── ПОЧЕМУ "use client" ───────────────────────────────────────────────────
// Обработка ошибок в React устроена через классовые компоненты и хуки,
// которые работают ТОЛЬКО в браузере. Поэтому файл обязан быть клиентским.
//
// ── ЧТО ТАКОЕ ERROR BOUNDARY ПРОСТЫМИ СЛОВАМИ ─────────────────────────────
// Это «сетка безопасности» вокруг части приложения. Если внутри что-то
// сломалось — падает только эта часть, а не всё приложение. Плеер внизу
// продолжает работать.
//
// В классовых компонентах для этого есть методы getDerivedStateFromError
// и componentDidCatch. В App Router Next.js берёт эту работу на себя —
// достаточно положить файл error.tsx.
// ============================================================================

import Link from "next/link";
import { useEffect } from "react";

type ErrorPageProps = {
  /** Объект ошибки. В production-сборке текст может быть обезличен. */
  error: Error & { digest?: string };
  /** Функция повторной попытки: заново отрисовывает сломанный участок. */
  reset: () => void;
};

export default function ErrorPage({ error, reset }: ErrorPageProps) {
  // Логируем ошибку. В реальном проекте здесь был бы вызов системы
  // мониторинга (Sentry и подобные).
  useEffect(() => {
    console.error("[error-boundary]", error);
  }, [error]);

  return (
    <div className="term-panel p-8 flex flex-col items-center gap-4 min-h-[40vh] justify-center">
      <pre className="text-alert text-[10px] sm:text-[12px] leading-tight glow" aria-hidden="true">{`
 ███████╗██████╗ ██████╗  ██████╗ ██████╗
 ██╔════╝██╔══██╗██╔══██╗██╔═══██╗██╔══██╗
 █████╗  ██████╔╝██████╔╝██║   ██║██████╔╝
 ██╔══╝  ██╔══██╗██╔══██╗██║   ██║██╔══██╗
 ███████╗██║  ██║██║  ██║╚██████╔╝██║  ██║
 ╚══════╝╚═╝  ╚═╝╚═╝  ╚═╝ ╚═════╝ ╚═╝  ╚═╝
`}</pre>

      {/*
        Греческая надпись ΣΦΑΛΜΑ ΣΥΣΤΗΜΑΤΟΣ — «сбой системы».
        Античный текст рядом с машинным сообщением об ошибке: ровно тот
        гибрид, на котором построено оформление проекта.
      */}
      <h1 className="text-[20px] tracking-[0.28em] text-alert glow">ΣΦΑΛΜΑ ΣΥΣΤΗΜΑΤΟΣ</h1>
      <p className="text-[11px] tracking-[0.14em] text-ink-muted">СБОЙ СИСТЕМЫ</p>

      {/*
        Показываем текст ошибки. Это осознанное решение для ЛИЧНОГО проекта:
        видеть причину полезнее, чем общее «что-то пошло не так».
        В публичном продукте так делать не стоит — в тексте ошибки могут
        быть внутренние детали.
      */}
      <p className="text-[11px] text-ink-muted text-center max-w-xl break-words">{error.message}</p>

      {/* digest — серверный идентификатор ошибки, по которому её можно
          найти в логах даже если текст скрыт. */}
      {error.digest && <p className="text-[10px] text-ink-faint">код: {error.digest}</p>}

      <div className="flex gap-2">
        <button type="button" className="term-btn" onClick={reset}>
          ⟳ ПОВТОРИТЬ
        </button>
        {/*
          Возврат на главную.

          Используем <Link> из next/link, а не обычный <a>: Link делает
          «мягкий» переход внутри приложения, без полной перезагрузки.

          Кнопка «ПОВТОРИТЬ» (reset) — более мягкое лечение: она пытается
          перерисовать только сломавшийся участок, не трогая остальное.
          Если не помогает — тогда переход на главную.
        */}
        <Link href="/" className="term-btn">
          ← НА ГЛАВНУЮ
        </Link>
      </div>
    </div>
  );
}
