// ============================================================================
// src/lib/scanner/metadata.ts — ЧТЕНИЕ ТЕГОВ ИЗ АУДИОФАЙЛОВ.
// ----------------------------------------------------------------------------
// mp3-файл — это не просто звук. Внутри него (или рядом с ним) лежат ТЕГИ:
// структурированные подписи с названием, исполнителем, альбомом, годом и
// даже картинкой обложки.
//
// ── КАКИЕ БЫВАЮТ ТЕГИ ──────────────────────────────────────────────────────
//   MP3   → ID3v1 (128 байт в конце файла) и ID3v2 (блок в начале)
//   FLAC  → Vorbis Comment
//   M4A   → iTunes-атомы (тот же формат, что у mp4-видео)
//   OGG   → Vorbis Comment
// Единого стандарта нет, поэтому мы пользуемся библиотекой music-metadata:
// она читает все форматы и приводит их к одной структуре.
//
// ── ГЛАВНАЯ ИДЕЯ ЭТОГО ФАЙЛА ───────────────────────────────────────────────
// «Лучше плохое название, чем никакого». Если тегов нет, мы придумываем
// значения сами: имя файла становится названием, папка — исполнителем.
// Именно поэтому пользователю не надо вручную описывать 500 песен.
// ============================================================================

import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";

import { parseFile } from "music-metadata";

import { COVERS_DIR } from "@/lib/config";

/**
 * То, что мы вытащили из файла. Ровно те поля, которые есть в таблице tracks.
 */
export type ParsedMetadata = {
  title: string;
  artist: string;
  album: string;
  albumArtist: string;
  genre: string;
  year: number;
  trackNumber: number;
  duration: number;
  /** Данные обложки и её формат — либо null, если картинки нет. */
  picture: { data: Uint8Array; format: string } | null;
};

/**
 * Приводит имя файла к «человеческому» виду — используется, когда тегов нет.
 *
 * ── ЧТО ДЕЛАЕТ ЦЕПОЧКА ────────────────────────────────────────────────────
 * "ATL - Ящик.mp3"
 *   1. path.parse(...).name        → "ATL - Ящик"     (убираем расширение)
 *   2. .replace(/\s*\[[^\]]*\]/g,"") → убираем [Official video] и подобное
 *   3. .replace(/\s+/g, " ")        → двойные пробелы в одинарные
 *   4. .trim()                      → обрезаем пробелы по краям
 *
 * Разбор регулярного выражения /\s*\[[^\]]*\]/g :
 *   \s*       — любое количество пробелов перед скобкой
 *   \[        — литеральный символ "["
 *   [^\]]*    — любое количество символов, КРОМЕ "]" (крышка ^ внутри
 *               квадратных скобок означает «не»)
 *   \]        — литеральный символ "]"
 *   флаг g    — искать все совпадения, а не только первое
 */
function titleFromFilename(filename: string): string {
  return path
    .parse(filename)
    .name.replace(/\s*[[(][^\])]*[\])]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Пытается угадать исполнителя и альбом по структуре папок.
 *
 * Типичная раскладка музыкальной библиотеки:
 *     /music/Linkin Park/Meteora/01 - Numb.mp3
 *                 └─ исполнитель └─ альбом
 *
 * Мы берём две последние папки перед файлом: первая — исполнитель,
 * вторая — альбом.
 *
 * ── ПРО КОРЕНЬ БИБЛИОТЕКИ ─────────────────────────────────────────────────
 * Важно не выйти за пределы корневой папки музыки: если файл лежит прямо
 * в /music/song.mp3, то «папкой исполнителя» окажется сам /music, и мы
 * подпишем все такие песни исполнителем "music". Поэтому мы сравниваем
 * найденную папку с корнем и в таком случае отдаём "Unknown".
 */
function guessFromFolders(absolutePath: string, musicRoot: string): { artist: string; album: string } {
  const fileDir = path.dirname(absolutePath);

  // path.relative вернёт путь ОТ корня К папке файла.
  //   "/music/ATL/Ящик" относительно "/music" → "ATL/Ящик"
  //   "/music"          относительно "/music" → "" (пустая строка)
  //   "/other"          относительно "/music" → "../other" (начинается с "..")
  const relative = path.relative(musicRoot, fileDir);

  // Файл лежит в корне библиотеки или вообще вне её — угадывать нечего.
  if (relative === "" || relative.startsWith("..")) {
    return { artist: "Unknown", album: "Unknown" };
  }

  // Разбиваем путь на части. path.sep — разделитель, свой для каждой ОС
  // ("/" в Linux и macOS, "\\" в Windows). Так код работает везде.
  const parts = relative.split(path.sep);

  if (parts.length === 1) {
    // /music/ATL/song.mp3 → исполнитель есть, альбома нет
    return { artist: parts[0], album: "Unknown" };
  }

  // /music/ATL/Ящик/song.mp3 → исполнитель и альбом
  // .at(-1) берёт последний элемент, .at(-2) — предпоследний.
  return { artist: parts.at(-2) ?? "Unknown", album: parts.at(-1) ?? "Unknown" };
}

/**
 * ГЛАВНАЯ ФУНКЦИЯ: читает метаданные одного файла.
 *
 * @param absolutePath — полный путь к файлу
 * @param filename     — имя файла (передаём отдельно, чтобы не считать заново)
 * @param musicRoot    — корень библиотеки (нужен для догадок по папкам)
 */
export async function readTrackMetadata(
  absolutePath: string,
  filename: string,
  musicRoot: string,
): Promise<ParsedMetadata> {
  const fallback = guessFromFolders(absolutePath, musicRoot);

  try {
    // ------------------------------------------------------------------------
    // parseFile читает файл и разбирает теги.
    //
    // Опция duration: true заставляет библиотеку посчитать ДЛИТЕЛЬНОСТЬ.
    // Для mp3 с постоянным битрейтом её можно вычислить по формуле
    // (размер / битрейт), а вот для VBR (переменного битрейта) приходится
    // честно проходить по всем фреймам — это медленнее, но точно.
    //
    // skipCovers по умолчанию false, то есть обложки читаются. Если бы
    // обложки были не нужны, их отключение ускорило бы скан: картинки
    // бывают по несколько мегабайт.
    // ------------------------------------------------------------------------
    const parsed = await parseFile(absolutePath, { duration: true });
    const common = parsed.common;

    // ------------------------------------------------------------------------
    // ВАЖНЫЙ МОМЕНТ ПРО ТИПЫ ДАННЫХ.
    //
    // Почти каждое поле из тегов имеет тип `string | undefined` — потому что
    // тега может не быть. Оператор `??` подставляет запасное значение.
    // А `?.` (optional chaining) безопасно обращается к свойству, которого
    // может не быть: `common.genre?.[0]` не упадёт, даже если genre === undefined.
    // ------------------------------------------------------------------------

    // genre в тегах — это МАССИВ жанров (их может быть несколько).
    // Берём первый, а если массива нет — пустую строку.
    const genre = common.genre?.[0] ?? "";

    // year — число, но тег может содержать мусор вроде "2023-05-01".
    // Number.isFinite проверяет, что получилось нормальное число,
    // а не NaN («Not a Number»).
    const rawYear = common.year;
    const year = typeof rawYear === "number" && Number.isFinite(rawYear) ? rawYear : 0;

    // Номер трека: common.track.no. Бывает, что тег содержит "3/12"
    // (третий из двенадцати) — библиотека уже разбирает это на .no и .of.
    const trackNumber = common.track.no ?? 0;

    // Длительность в секундах. `parsed.format.duration` может отсутствовать,
    // если файл повреждён — тогда честно ставим 0.
    const duration = parsed.format.duration ?? 0;

    // ------------------------------------------------------------------------
    // Обложка. common.picture — массив картинок. Обычно одна, но бывают
    // и лицевая, и задняя, и логотип лейбла. Берём первую.
    // ------------------------------------------------------------------------
    const firstPicture = common.picture?.[0];
    const picture =
      firstPicture && firstPicture.data.length > 0
        ? { data: firstPicture.data, format: firstPicture.format }
        : null;

    return {
      title: common.title?.trim() || titleFromFilename(filename),
      artist: common.artist?.trim() || fallback.artist,
      album: common.album?.trim() || fallback.album,
      // albumartist — «исполнитель альбома». Отличается от artist в сборниках:
      // песни разных исполнителей, но альбом один (например "VA - Танцы 90-х").
      // Если тега нет, логично считать исполнителем альбома основного артиста.
      albumArtist: common.albumartist?.trim() || common.artist?.trim() || fallback.artist,
      genre,
      year,
      trackNumber,
      duration,
      picture,
    };
  } catch (error) {
    // ------------------------------------------------------------------------
    // Файл битый, обрезанный или вообще не аудио. Не сдаёмся: возвращаем
    // то, что смогли угадать по имени и папкам. Пользователь хотя бы увидит
    // песню в списке и сможет её удалить из папки.
    // ------------------------------------------------------------------------
    console.warn(`[scanner] не удалось прочитать теги ${filename}:`, error);

    return {
      title: titleFromFilename(filename),
      artist: fallback.artist,
      album: fallback.album,
      albumArtist: fallback.artist,
      genre: "",
      year: 0,
      trackNumber: 0,
      duration: 0,
      picture: null,
    };
  }
}

/**
 * Сохраняет обложку на диск и возвращает ИМЯ файла (не путь!).
 *
 * ── ГЛАВНЫЙ ФОКУС: ДЕДУПЛИКАЦИЯ ЧЕРЕЗ ХЭШ ────────────────────────────────
 * У всех 12 треков одного альбома обложка ОДНА И ТА ЖЕ. Если сохранять её
 * для каждого трека отдельно, мы получим 12 копий одной картинки.
 *
 * Решение: имя файла = SHA-1 хэш от содержимого картинки.
 *   * у одинаковых картинок хэш одинаковый → файл запишется один раз;
 *   * у разных картинок хэш разный → коллизий практически не бывает.
 *
 * Это стандартный приём «content-addressable storage» — так же устроены
 * git (объекты по SHA) и Docker (слои образов по digest).
 *
 * Возвращаем только ИМЯ файла ("a3f1....png"), а не полный путь. Почему?
 * Потому что абсолютный путь зависит от машины: /home/august/... на домашнем
 * компьютере и /data/covers/... в Docker. Если хранить в базе полный путь,
 * база перестанет работать при переносе. Папку мы всегда знаем из конфига.
 */
export async function saveCoverIfNeeded(picture: { data: Uint8Array; format: string } | null): Promise<string | null> {
  if (!picture) return null;

  // --------------------------------------------------------------------------
  // Определяем расширение по MIME-типу картинки.
  // Тип "image/jpeg" → ".jpg" и так далее.
  // --------------------------------------------------------------------------
  const extension = picture.format === "image/png" ? ".png" : picture.format === "image/webp" ? ".webp" : ".jpg";

  // --------------------------------------------------------------------------
  // crypto.createHash("sha1") — функция из стандартной библиотеки Node/Bun.
  // .update(буфер) — «скормить» данные.
  // .digest("hex") — получить результат в виде hex-строки (0-9, a-f).
  //
  // Картинка приходит как Uint8Array (массив байт без знака). Buffer
  // в Node — это наследник Uint8Array, но createHash принимает и то, и другое.
  // --------------------------------------------------------------------------
  const hash = crypto.createHash("sha1").update(picture.data).digest("hex");
  const coverFile = `${hash}${extension}`;
  const targetPath = path.join(COVERS_DIR, coverFile);

  try {
    // ------------------------------------------------------------------------
    // Проверяем, нет ли уже такого файла. `fs.access` ничего не возвращает,
    // а просто бросает исключение, если файла нет. Это не самый изящный API,
    // но так исторически сложилось в Node.
    // ------------------------------------------------------------------------
    await fs.access(targetPath);
    // Файл уже есть — ничего не делаем. Вот она, дедупликация.
    return coverFile;
  } catch {
    // Файла нет — записываем.
    try {
      await fs.mkdir(COVERS_DIR, { recursive: true });
      await fs.writeFile(targetPath, picture.data);
      return coverFile;
    } catch (error) {
      console.warn(`[scanner] не удалось сохранить обложку ${coverFile}:`, error);
      return null;
    }
  }
}
