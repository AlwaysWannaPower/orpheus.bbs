// ============================================================================
// drizzle.config.ts — настройки инструмента drizzle-kit.
// ----------------------------------------------------------------------------
// drizzle-kit — это CLI-утилита (командная строка), а не код приложения.
// Она нужна только во время разработки и умеет:
//
//   drizzle-kit generate  — сравнить схему из schema.ts с папкой drizzle/
//                           и создать новый SQL-файл миграции;
//   drizzle-kit push      — применить схему к базе напрямую, без файлов
//                           (удобно на этапе экспериментов);
//   drizzle-kit studio    — поднять веб-интерфейс для просмотра данных.
//
// В рантайме (когда сайт работает) этот файл НЕ используется и в сборку
// не попадает. Он существует только для разработчика.
// ============================================================================

import { defineConfig } from "drizzle-kit";

export default defineConfig({
  // Где искать описание таблиц.
  schema: "./src/lib/db/schema.ts",

  // Куда складывать сгенерированные SQL-миграции.
  // Эти файлы МЫ КОММИТИМ В GIT — они и есть история изменений базы.
  out: "./drizzle",

  // Какая база используется.
  dialect: "sqlite",

  // Для команды `drizzle-kit push` (прямое применение схемы к базе).
  // Значение читается из переменной окружения или берётся по умолчанию.
  dbCredentials: {
    url: process.env.DB_PATH ?? "./data/music.db",
  },

  // Печатать подробности выполнения.
  verbose: true,

  // Спрашивать подтверждение перед потенциально разрушительными действиями
  // (например, УДАЛЕНИЕ колонки, в которой уже есть данные).
  strict: true,
});
