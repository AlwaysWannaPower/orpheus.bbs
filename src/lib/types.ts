// ============================================================================
// src/lib/types.ts — ТИПЫ, КОТОРЫМИ ОБМЕНИВАЮТСЯ СЕРВЕР И БРАУЗЕР.
// ----------------------------------------------------------------------------
// ── ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ? ──────────────────────────────────────────────────
// В проекте есть два мира:
//   1. СЕРВЕР — Server Components, Route Handlers. Он видит файловую систему,
//      базу, секреты. Здесь есть полные данные (например, абсолютный путь
//      к файлу).
//   2. БРАУЗЕР — Client Components. Он видит только то, что мы ему передали.
//
// Данные между этими мирами путешествуют через границу (boundary) и должны
// быть СЕРИАЛИЗУЕМЫМИ: только простые значения — строка, число, boolean,
// null, массив, обычный объект. Нельзя передать Date, функцию, класс,
// объект базы или файловый дескриптор.
//
// Поэтому мы вводим DTO (Data Transfer Object) — «транспортные» типы,
// специально подготовленные к отправке в браузер.
//
// ── ЧЕМ DTO ОТЛИЧАЕТСЯ ОТ TrackRow ИЗ СХЕМЫ ─────────────────────────────────
//   TrackRow — то, что лежит в БАЗЕ (Date, все колонки, включая path).
//   TrackDTO  — то, что уезжает в БРАУЗЕР (числа вместо Date, без path).
// Эти типы не совпадают, и это хорошо: мы осознанно решаем, что показывать.
// Функция toTrackDTO() в queries.ts выполняет превращение одного в другое.
// ============================================================================

/**
 * Один трек в том виде, в каком его видит интерфейс.
 *
 * Обрати внимание: здесь НЕТ поля path (абсолютный путь на диске).
 * И не потому, что лень — а потому что:
 *   * браузеру он не нужен (файл отдаётся через /api/tracks/:id/stream);
 *   * раскрывать структуру папок сервера наружу — плохая практика.
 * Принцип «отдавай минимум необходимого» называется принципом наименьших
 * привилегий и встречается в безопасности повсюду.
 */
export type TrackDTO = {
  id: number;
  /** Заголовок: из тега title или из имени файла. */
  title: string;
  /** Исполнитель: из тега artist или "Unknown". */
  artist: string;
  /** Альбом: из тега album или "Unknown". */
  album: string;
  albumArtist: string;
  genre: string;
  /** Год выпуска, 0 если неизвестен. */
  year: number;
  /** Номер трека в альбоме, 0 если неизвестен. */
  trackNumber: number;
  /** Длительность в СЕКУНДАХ (дробная). Форматируем в "3:45" в format.ts. */
  duration: number;
  /** Размер файла в байтах — показываем в списке треков. */
  size: number;
  isFavorite: boolean;
  /** Есть ли у трека извлечённая обложка (тогда можно грузить /api/tracks/id/cover). */
  hasCover: boolean;
  /** Когда трек появился в библиотеке. Unix-время в МИЛЛИСЕКУНДАХ. */
  addedAt: number;
};

/**
 * Агрегат по альбому — результат SQL-запроса с GROUP BY.
 * Подробный разбор самого запроса — в src/lib/db/queries.ts.
 */
export type AlbumDTO = {
  album: string;
  albumArtist: string;
  year: number;
  /** Сколько треков в альбоме (COUNT(*) в SQL). */
  trackCount: number;
  /** Суммарная длительность всех треков альбома в секундах (SUM(duration)). */
  totalDuration: number;
  /** id любого трека альбома — нужен, чтобы взять его обложку. */
  coverTrackId: number | null;
};

/** Агрегат по исполнителю — тоже GROUP BY. */
export type ArtistDTO = {
  artist: string;
  trackCount: number;
  albumCount: number;
};

/** Плейлист вместе с количеством треков в нём. */
export type PlaylistDTO = {
  id: number;
  name: string;
  description: string | null;
  trackCount: number;
  /** Unix-время в миллисекундах. */
  createdAt: number;
};

/** Одна запись истории прослушиваний «трек + когда играл». */
export type HistoryEntryDTO = {
  playedAt: number;
  track: TrackDTO;
};

/**
 * Состояние плеера, сохранённое на сервере.
 * Используется для функции «Продолжить слушать».
 */
export type PlaybackStateDTO = {
  track: TrackDTO | null;
  /** Позиция внутри трека в секундах. */
  position: number;
};

/**
 * Результат сканирования библиотеки. Отдаётся браузеру как JSON,
 * чтобы интерфейс мог показать красивый отчёт вида:
 *   "Добавлено 120, обновлено 3, удалено 0, пропущено 480".
 */
export type ScanResultDTO = {
  /** Сколько файлов обошли (все найденные аудиофайлы). */
  filesFound: number;
  /** Сколько новых записей добавили. */
  added: number;
  /** Сколько существующих обновили (изменились теги или файл). */
  updated: number;
  /** Сколько записей удалили, потому что файлов больше нет. */
  removed: number;
  /** Сколько пропустили, потому что файл не изменился (mtime + size совпали). */
  skipped: number;
  /** Файлы, которые не удалось прочитать (битые, нет прав). */
  errors: string[];
  /** Сколько миллисекунд занял скан — чтобы видеть эффект оптимизаций. */
  durationMs: number;
};

/** Как сортировать список треков. Строковый union — тип «одно из». */
export type TrackSortKey = "added_desc" | "title_asc" | "artist_asc" | "album_asc" | "duration_desc";
