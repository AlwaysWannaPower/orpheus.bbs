import { Fira_Mono } from "next/font/google";
import { cookies } from "next/headers";

import { AppHeader } from "@/components/layout/AppHeader";
import { Sidebar } from "@/components/layout/Sidebar";
import { PlayerBar } from "@/components/player/PlayerBar";
import { PlayerProvider } from "@/components/player/player-context";
import { BRANDING } from "@/config/branding";
import { THEME_COOKIE, getThemeDefinition, resolveThemeId } from "@/themes/registry";

import "./globals.css";

// ============================================================================
// ПОДКЛЮЧЕНИЕ ШРИФТА.
// ----------------------------------------------------------------------------
// next/font/google скачивает шрифт ВО ВРЕМЯ СБОРКИ и раздаёт его со своего
// домена. Что это даёт:
//   * нет запроса к fonts.googleapis.com из браузера (быстрее и приватнее);
//   * нет «прыжка» текста при загрузке (display: swap + метрики шрифта);
//   * файл шрифта попадает в общий кэш статики проекта.
//
// ── ПОЧЕМУ FIRA MONO ──────────────────────────────────────────────────────
// Требований к шрифту было три, и они конфликтовали друг с другом:
//   1. моноширинный — обязательное условие терминальной эстетики;
//   2. КИРИЛЛИЦА — интерфейс на русском;
//   3. ГРЕЧЕСКИЙ — название ΟΡΦΕΥΣ и подписи тем.
//
// Первым кандидатом был IBM Plex Mono (стоит в большинстве проектов),
// но у него в наборе Google Fonts НЕТ греческого сабсета:
//     subsets?: 'cyrillic' | 'cyrillic-ext' | 'latin' | 'latin-ext' | 'vietnamese'
// То есть греческие буквы отрисовались бы запасным системным шрифтом —
// другим по ширине и стилю, и строка «поехала» бы.
//
// У Fira Mono есть всё нужное сразу:
//     subsets: cyrillic, cyrillic-ext, greek, greek-ext, latin, latin-ext
//
// Вывод на будущее: прежде чем выбирать шрифт «по красоте», проверь
// в типах next/font, какие subset-ы он реально поддерживает.
//
// ── ПРО SUBSETS ───────────────────────────────────────────────────────────
// Subset — это набор символов. Каждый subset это отдельный файл шрифта,
// который браузер скачивает. Поэтому не стоит указывать «всё подряд»:
// страница станет тяжелее без пользы.
//
// Нам нужны три:
//   latin    — латиница (интерфейс частично на ней, названия треков);
//   cyrillic — русский текст (без него он отрисуется системным шрифтом
//              и стиль развалится);
//   greek    — греческие буквы в названии проекта.
// ============================================================================
const terminalMono = Fira_Mono({
  variable: "--font-terminal",
  subsets: ["latin", "cyrillic", "greek"],
  // Три начертания вместо девяти: 400 — текст, 500 — акценты, 700 — заголовки.
  weight: ["400", "500", "700"],
  display: "swap",
});

// ============================================================================
// МЕТАДАННЫЕ
// ============================================================================
export const metadata: Metadata = {
  // Значения берутся из BRANDING — имя проекта объявлено ровно в одном месте
  // (src/config/branding.ts). Переименовать проект = поправить одну строку.
  title: `${BRANDING.name} — ${BRANDING.taglineEn}`,
  description:
    "Локальная музыкальная библиотека: сканирование папки, чтение тегов, поиск, плейлисты, история и потоковое воспроизведение с поддержкой HTTP Range.",
};

// ============================================================================
// VIEWPORT — отдельный экспорт (в новых версиях Next.js его вынесли из
// metadata; это одно из изменений API, о которых предупреждает AGENTS.md).
//
// ── ПОЧЕМУ ФУНКЦИЯ, А НЕ КОНСТАНТА ────────────────────────────────────────
// themeColor — это цвет адресной строки мобильного браузера. Он должен
// совпадать с фоном САЙТА, иначе сверху появляется чужая цветная полоса.
//
// Но фон зависит от выбранной темы: у «Эгейского моря» он почти чёрный,
// у «Александрии» — светлый папирус. Значит, значение должно вычисляться
// на каждом запросе, а не задаваться один раз при сборке.
//
// Поэтому используется generateViewport() — асинхронная функция. Она
// читает ту же cookie, что и сам layout, и берёт первый цвет темы из её
// палитры (swatches[0] — это всегда цвет фона).
// ============================================================================
export async function generateViewport(): Promise<Viewport> {
  const cookieStore = await cookies();
  const themeId = resolveThemeId(cookieStore.get(THEME_COOKIE)?.value);

  const theme = getThemeDefinition(themeId);

  return {
    width: "device-width",
    initialScale: 1,
    themeColor: theme.swatches[0],
  };
}

export default async function RootLayout({ children }: LayoutProps<"/">) {
  // --------------------------------------------------------------------------
  // ЧТЕНИЕ ТЕМЫ ИЗ COOKIE.
  //
  // ── ЗАЧЕМ ЭТО ДЕЛАЕТСЯ НА СЕРВЕРЕ ────────────────────────────────────────
  // Сервер должен сразу вставить правильный data-theme в HTML. Если этого
  // не сделать, браузер сначала покажет тему по умолчанию, а потом
  // переключится на сохранённую — пользователь увидит вспышку чужих цветов.
  //
  // ── ПОЧЕМУ await ─────────────────────────────────────────────────────────
  // В Next.js 15+ функции cookies(), headers(), params и searchParams
  // асинхронные. Это ещё одна «ломающая перемена», о которой надо помнить.
  //
  // Побочный эффект: обращение к cookies() делает ВСЁ приложение динамическим
  // (рендер при каждом запросе). Для локального плеера это и нужно: данные
  // в базе меняются, кэшировать страницы нельзя.
  // --------------------------------------------------------------------------
  const cookieStore = await cookies();
  const themeId = resolveThemeId(cookieStore.get(THEME_COOKIE)?.value);

  // --------------------------------------------------------------------------
  // ТОКЕН ДОСТУПА К АУДИО.
  //
  // ── ПОЧЕМУ ОН ЧИТАЕТСЯ ЗДЕСЬ, А НЕ В КОМПОНЕНТЕ ПЛЕЕРА ───────────────────
  // Переменные окружения без префикса NEXT_PUBLIC_ доступны ТОЛЬКО на
  // сервере. Это защита: в .env лежат ключи и пароли, и они не должны
  // попадать в JavaScript, который скачивает браузер.
  //
  // Но токен нужен браузеру — иначе он не сможет собрать адрес потока.
  // Поэтому решение такое: сервер читает переменную в момент ЗАПРОСА
  // и передаёт значение в клиент обычным пропсом.
  //
  // ── АЛЬТЕРНАТИВА, КОТОРАЯ НЕ РАБОТАЕТ ────────────────────────────────────
  // Можно было бы назвать переменную NEXT_PUBLIC_STREAM_TOKEN и читать её
  // прямо в браузере. Но такие переменные подставляются в код В МОМЕНТ
  // СБОРКИ. В Docker сборка (`docker compose build`) идёт раньше, чем
  // применяются переменные из `environment:` (`docker compose up`) —
  // и в бандл уезжает пустая строка. Подробный разбор — в src/lib/stream-url.ts.
  //
  // Пустая строка = проверка доступа выключена (удобно для локальной работы).
  // --------------------------------------------------------------------------
  const streamToken = process.env.STREAM_TOKEN?.trim() ?? "";

  return (
    <html
      lang="ru"
      // data-theme — ключевой атрибут всей дизайн-системы.
      // CSS-файлы тем выглядят так: html[data-theme="gibson"] { --color-... }
      // Сменил атрибут — сменилось всё оформление. Ни один компонент
      // при этом не меняется.
      data-theme={themeId}
      className={`${terminalMono.variable} h-full`}
      // ----------------------------------------------------------------------
      // suppressHydrationWarning — ОСОЗНАННОЕ отключение проверки для одного
      // этого элемента.
      //
      // ── ЧТО ЗДЕСЬ ПРОИСХОДИТ ─────────────────────────────────────────────
      // React сверяет HTML, пришедший с сервера, с тем, что он собирается
      // отрисовать в браузере. Если они различаются — это «ошибка гидратации».
      //
      // Но в <html> УЖЕ ВМЕШИВАЮТСЯ посторонние: расширения браузера
      // дописывают туда свои атрибуты. Например:
      //   * Dark Reader  → data-darkreader-proxy-injected="true"
      //   * Trancy       → trancy-version="7.9.4"
      // Наш сервер об этих атрибутах знать не может физически, поэтому React
      // считает разметку несовпадающей и ругается в консоль.
      //
      // Отключить расширения пользователя мы не можем. Поэтому React
      // предоставляет официальный «выход»: этот проп говорит «не проверяй
      // атрибуты именно этого элемента». Он НЕ отключает проверку детей —
      // ошибки гидратации в нашем собственном коде по-прежнему будут видны.
      //
      // Ставить его куда-либо ещё (на div-ы, на компоненты) НЕЛЬЗЯ:
      // так можно случайно спрятать настоящий баг.
      // ----------------------------------------------------------------------
      suppressHydrationWarning
    >
      <body className="min-h-full antialiased">
        {/*
          Оборачиваем ВСЁ приложение в провайдер плеера.
          Внутри него создаётся <audio> и живут три контекста с состоянием.
        */}
        <PlayerProvider streamToken={streamToken}>
          {/*
            flex-col + min-h-screen прижимают панель плеера к низу экрана,
            даже когда контента мало. flex-1 у блока с контентом растягивает
            его на всё свободное место.
          */}
          <div className="min-h-screen flex flex-col">
            <AppHeader />

            <div className="flex-1 flex flex-col lg:flex-row w-full mx-auto max-w-[1600px]">
              <Sidebar themeId={themeId} />

              {/*
                <main> — семантический тег: «здесь основное содержимое
                страницы». Скринридеры умеют переходить сразу к нему,
                пропуская навигацию.
              */}
              <main className="flex-1 min-w-0 p-3">{children}</main>
            </div>

            <PlayerBar />
          </div>
        </PlayerProvider>
      </body>
    </html>
  );
}
