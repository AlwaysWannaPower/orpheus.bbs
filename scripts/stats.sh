#!/usr/bin/env bash
# ============================================================================
# scripts/stats.sh — СКОЛЬКО РЕСУРСОВ ЕСТ ПРОЕКТ.
# ----------------------------------------------------------------------------
# Отвечает на вопрос «сколько памяти и процессора забирает плеер».
#
# ЗАПУСК:
#     ./scripts/stats.sh              измерить локальный процесс
#     ./scripts/stats.sh --watch      обновлять каждые 5 секунд (Ctrl+C — выход)
#     ./scripts/stats.sh --docker     измерить контейнер
#     bun run stats                   то же, что первый вариант
#
# ── ЧЕМ ЭТОТ СКРИПТ ЛУЧШЕ КОМАНДЫ ps ──────────────────────────────────────
# `ps` показывает СРЕДНИЙ процент процессора за всё время жизни процесса.
# Это бесполезно: сервер, который грузился минуту при старте и потом стоит
# без дела, покажет «высокую загрузку» ещё долго.
#
# Скрипт считает НАСТОЯЩУЮ текущую загрузку: берёт суммарное процессорное
# время процесса, ждёт несколько секунд, берёт снова и делит разницу на
# прошедшее время. Это единственный честный способ.
#
# ── ЧТО ТАКОЕ RSS И VSZ ───────────────────────────────────────────────────
#   RSS (Resident Set Size) — сколько ФИЗИЧЕСКОЙ памяти реально занято.
#                             Это и есть интересующее нас число.
#   VSZ (Virtual Size)      — сколько ВИРТУАЛЬНОГО адресного пространства
#                             процесс попросил у системы. У современных
#                             рантаймов это гигабайты, и это НОРМАЛЬНО:
#                             виртуальная память — не потраченная память.
#                             Не пугайся VSZ, смотри на RSS.
# ============================================================================

set -u

# Цвета для вывода (если терминал их поддерживает).
BOLD=$'\033[1m'; DIM=$'\033[2m'; GREEN=$'\033[32m'; YELLOW=$'\033[33m'; CYAN=$'\033[36m'; RESET=$'\033[0m'

MODE="local"
WATCH=0
for arg in "$@"; do
  case "$arg" in
    --docker) MODE="docker" ;;
    --watch)  WATCH=1 ;;
    *) echo "Неизвестный аргумент: $arg"; exit 1 ;;
  esac
done

# ---------------------------------------------------------------------------
# Поиск PID процесса сервера.
#
# ── ВАЖНАЯ ТОНКОСТЬ ПРО BUN ────────────────────────────────────────────────
# Проект работает на рантайме Bun, но в списке процессов он может называться
# «node»: Bun подменяет имя процесса ради совместимости с инструментами,
# которые ищут именно node. Поэтому искать по имени бесполезно.
#
# Настоящий исполняемый файл виден только через символическую ссылку
# /proc/<PID>/exe. Именно так мы и проверяем.
# ---------------------------------------------------------------------------
find_server_pid() {
  # ── ПОЧЕМУ ВЫБИРАЕМ ПО НАИБОЛЬШЕЙ ПАМЯТИ ─────────────────────────────────
  # Команда `bun run start` порождает ДВА процесса:
  #
  #     bun --bun run next start      ← обёртка, которая просто запускает дочерний
  #       └── next start              ← вот это и есть настоящий сервер
  #
  # В командной строке обоих есть «next start», поэтому pgrep вернёт оба.
  # Обёртка занимает 5–10 МБ, сервер — сотни мегабайт.
  #
  # Самый простой и надёжный критерий — взять процесс с НАИБОЛЬШИМ RSS:
  # настоящий сервер всегда потребляет памяти больше обёртки.
  # ---------------------------------------------------------------------------
  local best_pid=""
  local best_rss=0

  for pid in $(pgrep -f "next start" 2>/dev/null); do
    local exe rss
    exe=$(readlink "/proc/$pid/exe" 2>/dev/null || echo "")

    # Интересуют только процессы, исполняемые рантаймом Bun или Node.
    case "$exe" in
      *bun|*node) ;;
      *) continue ;;
    esac

    rss=$(awk '/VmRSS/{print $2}' "/proc/$pid/status" 2>/dev/null || echo 0)
    if [ "${rss:-0}" -gt "$best_rss" ]; then
      best_rss="$rss"
      best_pid="$pid"
    fi
  done

  if [ -n "$best_pid" ]; then
    echo "$best_pid"
    return 0
  fi
  return 1
}

# ---------------------------------------------------------------------------
# Чтение RSS процесса в мегабайтах.
# Берём из /proc/<PID>/status — это простой текстовый файл с готовыми полями.
# ---------------------------------------------------------------------------
read_rss_mb() {
  awk '/VmRSS/{printf "%.1f", $2/1024}' "/proc/$1/status" 2>/dev/null || echo "0"
}

# ---------------------------------------------------------------------------
# Чтение суммарного процессорного времени процесса.
#
# Файл /proc/<PID>/stat содержит много чисел подряд. Нас интересуют
# 14-е и 15-е поля: utime (время в пользовательском режиме) и stime
# (в режиме ядра), оба в «тиках» — единицах планировщика.
#
# Нужно разделить их на константу CLK_TCK (обычно 100), чтобы получить
# секунды. Узнать её можно командой getconf CLK_TCK.
# ---------------------------------------------------------------------------
read_cpu_ticks() {
  awk '{print $14+$15}' "/proc/$1/stat" 2>/dev/null || echo "0"
}

# ---------------------------------------------------------------------------
# Подробный отчёт по локальному процессу.
# ---------------------------------------------------------------------------
report_local_once() {
  local pid
  if ! pid=$(find_server_pid); then
    echo "${YELLOW}Процесс сервера не найден.${RESET}"
    echo "${DIM}Запусти в другом окне:  bun run dev   (или bun run start)${RESET}"
    return 1
  fi

  local exe rss vsz threads
  exe=$(readlink "/proc/$pid/exe" 2>/dev/null || echo "?")
  rss=$(read_rss_mb "$pid")
  vsz=$(awk '/VmSize/{printf "%.0f", $2/1024}' "/proc/$pid/status" 2>/dev/null)
  threads=$(awk '/Threads/{print $2}' "/proc/$pid/status" 2>/dev/null)

  echo "${BOLD}── ПРОЦЕСС ────────────────────────────────────────${RESET}"
  printf "  PID:            %s\n" "$pid"
  # Показываем реальный исполняемый файл — так видно, что это Bun,
  # хотя в списке процессов он может называться node.
  printf "  Рантайм:        %s\n" "$exe"
  printf "  RSS (память):   %s %sМБ%s\n" "$GREEN" "$rss" "$RESET"
  # VSZ намеренно показываем с пометкой «не пугаться» — у рантаймов
  # JavaScript он всегда огромный и это нормально.
  printf "  VSZ (вирт.):    %s МБ  ${DIM}(не пугаться: виртуальная память ≠ занятая)${RESET}\n" "${vsz:-?}"
  printf "  Потоков:        %s\n" "${threads:-?}"

  # ---- Измерение процессора: два снимка с паузой -------------------------
  local hz a b cpu
  hz=$(getconf CLK_TCK)
  a=$(read_cpu_ticks "$pid")
  sleep 5
  b=$(read_cpu_ticks "$pid")
  cpu=$(awk -v a="$a" -v b="$b" -v hz="$hz" 'BEGIN{printf "%.2f", (b-a)/hz/5*100}')

  echo
  echo "${BOLD}── ПРОЦЕССОР (за последние 5 секунд) ──────────────${RESET}"
  printf "  Загрузка:       %s%s%%${RESET}\n" "$CYAN" "$cpu"
  echo "  ${DIM}0–2% в простое — нормально. Плеер ничего не делает, пока не играет.${RESET}"

  echo
  echo "${BOLD}── МАШИНА ─────────────────────────────────────────${RESET}"
  free -h 2>/dev/null | awk 'NR==1{print "  "$0} NR==2{print "  "$0}'
  echo
  echo "${DIM}Совет: сравни RSS до и после действий (прокрутить библиотеку, послушать музыку).${RESET}"
  echo "${DIM}Рост RSS «ступеньками» и без возврата — это работа сборщика мусора, а не утечка.${RESET}"
}

# ---------------------------------------------------------------------------
# Режим Docker: используем встроенную команду docker stats.
# Формат вывода настраивается через --format (шаблон Go).
# ---------------------------------------------------------------------------
report_docker_once() {
  local name="${CONTAINER_NAME:-orpheus-bbs}"

  if ! docker inspect "$name" >/dev/null 2>&1; then
    echo "${YELLOW}Контейнер «$name» не найден.${RESET}"
    echo "${DIM}Запусти:  docker compose up -d${RESET}"
    echo "${DIM}Имя можно переопределить:  CONTAINER_NAME=другое ./scripts/stats.sh --docker${RESET}"
    return 1
  fi

  echo "${BOLD}── КОНТЕЙНЕР «$name» ──────────────────────────────${RESET}"
  # Полей много, поэтому берём только нужные:
  #   CPUPerc  — загрузка процессора в процентах
  #   MemUsage — «занято / лимит»
  #   MemPerc  — доля от лимита
  #   NetIO    — сетевой трафик
  #   BlockIO  — чтение/запись диска
  #   PIDs     — число процессов внутри контейнера
  docker stats --no-stream --format \
    "  Процессор:   {{.CPUPerc}}
  Память:      {{.MemUsage}}  ({{.MemPerc}})
  Сеть:        {{.NetIO}}
  Диск:        {{.BlockIO}}
  Процессов:   {{.PIDs}}" "$name"

  echo
  echo "${DIM}Лимит памяти, если задан в docker-compose.yml, будет виден в скобках.${RESET}"
  echo "${DIM}Без лимита MemUsage показывает всю память машины как доступную.${RESET}"
}

# ---------------------------------------------------------------------------
# Главный цикл.
# ---------------------------------------------------------------------------
if [ "$WATCH" -eq 1 ]; then
  # Режим наблюдения: обновляем экран каждые 5 секунд.
  # clear очищает терминал, чтобы вывод не «ехал» вниз бесконечно.
  while true; do
    clear
    echo "${DIM}$(date '+%H:%M:%S') — обновление каждые 5 секунд, выход по Ctrl+C${RESET}"
    echo
    if [ "$MODE" = "docker" ]; then report_docker_once; else report_local_once; fi
    sleep 5
  done
else
  if [ "$MODE" = "docker" ]; then report_docker_once; else report_local_once; fi
fi
