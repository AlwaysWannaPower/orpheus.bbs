// ============================================================================
// src/app/api/scan/route.ts — ЗАПУСК СКАНИРОВАНИЯ БИБЛИОТЕКИ.
// ----------------------------------------------------------------------------
// URL: POST /api/scan
//
// Почему POST, а не GET? Потому что этот запрос ИЗМЕНЯЕТ состояние сервера
// (пишет в базу). Правило HTTP: GET должен быть безопасным (safe) — его можно
// повторять сколько угодно раз без последствий, и браузер вправе закэшировать
// результат. Скан кэшировать нельзя, поэтому POST.
//
// ── ПОЧЕМУ СКАН ДЛИТСЯ ДОЛГО ──────────────────────────────────────────────
// Чтение тегов у сотен файлов — это секунды, а иногда десятки секунд.
// Мы делаем это синхронно внутри одного HTTP-запроса: пользователь нажал
// «СКАНИРОВАТЬ» и ждёт ответа с отчётом. Для домашней библиотеки это
// нормально и максимально просто.
//
// Если однажды библиотека станет огромной, правильный путь — фоновая задача
// с прогрессом через Server-Sent Events (SSE). Но это уже следующий уровень
// сложности, и в ТЗ он не требуется.
// ============================================================================

import { handleApiError, json, noStoreHeaders } from "@/lib/api-helpers";
import { scanMusicLibrary } from "@/lib/scanner";

// Скан всегда выполняет свежую работу — никакого кэша.
export const dynamic = "force-dynamic";

export async function POST(): Promise<Response> {
  try {
    // Вся логика лежит в lib/scanner — Route Handler остаётся тонким.
    // Это хорошая практика: обработчик отвечает за HTTP, а не за бизнес-логику.
    const result = await scanMusicLibrary();

    return json(result, { headers: noStoreHeaders });
  } catch (error) {
    return handleApiError(error);
  }
}
