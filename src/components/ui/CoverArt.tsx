"use client";

// ============================================================================
// src/components/ui/CoverArt.tsx — ОБЛОЖКА АЛЬБОМА С ЗАГЛУШКОЙ.
// ----------------------------------------------------------------------------
// Маленький, но поучительный компонент. Здесь встречаются сразу три важные
// темы: клиентские компоненты, обработка ошибок загрузки картинок и
// почему иногда <img> лучше, чем <Image> из Next.js.
// ============================================================================

import { useState } from "react";

type CoverArtProps = {
  trackId: number;
  hasCover: boolean;
  /** Размер в пикселях (квадрат). */
  size?: number;
  /** Подпись для скринридера — что за картинка. */
  alt?: string;
};

export function CoverArt({ trackId, hasCover, size = 40, alt = "Обложка альбома" }: CoverArtProps) {
  // --------------------------------------------------------------------------
  // СОСТОЯНИЕ ОШИБКИ.
  //
  // onError у <img> срабатывает, если картинка не загрузилась: файл пропал,
  // сеть отвалилась, сервер вернул 404. Обложка — вещь необязательная, и
  // из-за неё ломать интерфейс нельзя: показываем ASCII-заглушку.
  //
  // Начальное значение (false) вычисляется при каждом рендере, но useState
  // использует его только при ПЕРВОМ. Это важно: если hasCover изменится
  // (например, после сканирования), ошибка не сбросится автоматически.
  // --------------------------------------------------------------------------
  const [hasError, setHasError] = useState(false);

  const showPlaceholder = !hasCover || hasError;

  return (
    <div
      // inline-flex + размеры через style — потому что размер приходит
      // из пропса и может быть любым. Tailwind-классы генерируются заранее
      // и не умеют принимать произвольные числа без специального синтаксиса.
      className="shrink-0 inline-flex items-center justify-center border border-line bg-canvas overflow-hidden"
      style={{ width: size, height: size }}
    >
      {showPlaceholder ? (
        // --------------------------------------------------------------------
        // ЗАГЛУШКА.
        //
        // role="img" + aria-label — так скринридер (программа для незрячих)
        // поймёт, что это картинка, и прочитает описание. Просто <div> без
        // роли для него — пустое место.
        //
        // aria-hidden="true" на тексте говорит: «не читай этот символ»,
        // он декоративный.
        // --------------------------------------------------------------------
        <span
          role="img"
          aria-label="Обложка отсутствует"
          className="text-ink-faint leading-none select-none"
          style={{ fontSize: size * 0.55 }}
        >
          <span aria-hidden="true">♪</span>
        </span>
      ) : (
        // --------------------------------------------------------------------
        // ПОЧЕМУ ОБЫЧНЫЙ <img>, А НЕ <Image> ИЗ NEXT.JS
        //
        // Компонент <Image> из next/image умеет оптимизацию: он сжимает
        // картинки, отдаёт их в современном формате (WebP/AVIF) и генерирует
        // адаптивные размеры. Это отлично работает для картинок сайта.
        //
        // Но у него есть цена: на каждый уникальный размер нужно настроить
        // конфигурацию, а оптимизация выполняется сервером — то есть для
        // 500 обложек мы получим 500 дополнительных проходов сжатия.
        // Наши обложки уже лежат готовыми файлами и отдаются с заголовком
        // immutable (см. /api/tracks/[id]/cover), поэтому экономить нечего.
        //
        // Мораль: <Image> — отличный инструмент, но не религия. Для готовых
        // локальных файлов обычный <img> проще и быстрее.
        // --------------------------------------------------------------------
        // eslint-disable-next-line @next/next/no-img-element
        <img
          src={`/api/tracks/${trackId}/cover`}
          alt={alt}
          width={size}
          height={size}
          // loading="lazy" — браузер не станет грузить картинку, пока она
          // не приблизится к видимой области. Для списка из 500 треков это
          // экономит сотни запросов при открытии страницы.
          loading="lazy"
          decoding="async"
          className="w-full h-full object-cover"
          onError={() => setHasError(true)}
        />
      )}
    </div>
  );
}
