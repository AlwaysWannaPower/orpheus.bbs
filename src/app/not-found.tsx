// ============================================================================
// src/app/not-found.tsx — СТРАНИЦА 404 («ПУТЬ НЕ НАЙДЕН»).
// ----------------------------------------------------------------------------
// Next.js показывает этот файл, когда:
//   * пользователь открыл несуществующий адрес;
//   * страница вызвала функцию notFound().
//
// ── ВАЖНО ПРО HTTP-КОД ────────────────────────────────────────────────────
// При вызове notFound() Next.js отвечает статусом 404. Это принципиально:
// поисковые роботы и любые внешние программы должны понимать, что страницы
// НЕТ, а не что она «есть, но странная».
//
// (В проекте была история, когда из-за корневого loading.tsx статус
//  срывался на 200 — разбор в docs/04-nextjs-app-router.md, §8.1.)
//
// ── ОФОРМЛЕНИЕ ────────────────────────────────────────────────────────────
// Греческая надпись ΟΔΟΣ ΑΦΑΝΗΣ — «невидимый путь». Рядом технический
// код 404. Это и есть гибрид: античный текст плюс машинный номер ошибки.
// ============================================================================

import Link from "next/link";

import { BRANDING } from "@/config/branding";

export default function NotFound() {
  return (
    <div className="term-panel fade-up flex min-h-[40vh] flex-col items-center justify-center gap-5 p-8">
      {/* Орнамент — визуальная рамка, общая для всех «служебных» страниц. */}
      <div className="motif-meander w-full max-w-xs text-line-strong" aria-hidden="true" />

      {/*
        ASCII-рисунок сломанной колонны.

        <pre> сохраняет пробелы и переводы строк — в обычном <div> браузер
        «съел» бы всё форматирование, и рисунок схлопнулся бы в строку.

        aria-hidden — скринридер не должен читать набор символов.
      */}
      <pre className="text-center text-[11px] leading-tight text-alert glow" aria-hidden="true">{`
   ▄▄▄▄▄▄▄▄▄
   █ 4 0 4 █
   ▀▀▀▀▀▀▀▀▀
    ┃ ┃ ┃ ┃
    ┃ ┃ ╱ ┃      ← колонна сломана
    ┃ ╱ ┃ ┃
   ▄▄▄▄▄▄▄▄▄
`}</pre>

      <h1 className="text-[20px] tracking-[0.3em] text-accent glow">ΟΔΟΣ ΑΦΑΝΗΣ</h1>

      <p className="text-center text-[12px] tracking-[0.1em] text-ink-muted">
        РЕСУРС НЕ НАЙДЕН · такой страницы в архиве нет
      </p>

      <p className="max-w-md text-center text-[11px] leading-relaxed text-ink-muted">
        Возможно, плейлист был удалён или в адресе опечатка. Музыкальные файлы
        при этом никуда не пропали — они лежат на диске.
      </p>

      <div className="motif-meander w-full max-w-xs text-line-strong" aria-hidden="true" />

      {/*
        Ссылка возврата. Используем <Link>, а не <a>: Link делает «мягкий»
        переход без перезагрузки — музыка продолжит играть.
      */}
      <Link href="/" className="term-btn">
        ← ВЕРНУТЬСЯ В {BRANDING.name}
      </Link>
    </div>
  );
}
