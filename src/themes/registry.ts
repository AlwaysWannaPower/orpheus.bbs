/**
 * Тема по умолчанию.
 *
 * `THEMES[0].id` вместо строки "aegean" — чтобы при перестановке массива
 * значение подтянулось само и не разъехалось.
 */
export const DEFAULT_THEME: ThemeId = THEMES[0].id;

/**
 * Имя cookie, в котором хранится выбранная тема.
 *
 * ── ПОЧЕМУ COOKIE, А НЕ localStorage ──────────────────────────────────────
 * Это важно, и вот почему. Страница рендерится на СЕРВЕРЕ. Сервер должен
 * сразу вставить в HTML правильный атрибут `<html data-theme="...">`,
 * иначе произойдёт одно из двух:
 *
 *   1. Мелькнёт неправильная тема (FOUC — flash of unstyled content),
 *      потому что сервер отдал одну, а браузер потом переключил на другую.
 *   2. Либо возникнет ошибка гидратации, если React увидит, что атрибут
 *      на сервере и в браузере не совпадает.
 *
 * Но `localStorage` серверу недоступен — это API браузера. А вот cookie
 * приходит на сервер вместе с каждым запросом. Поэтому тему храним в cookie:
 * сервер читает её и сразу рисует нужный вариант.
 *
 * Вывод на будущее: **всё, что влияет на серверный рендеринг, храни в cookie,
 * а не в localStorage**.
 */
export const THEME_COOKIE = "orpheus_theme";

/**
 * Проверяет, что строка — действительно идентификатор известной темы.
 *
 * Это TYPE GUARD: возвращаемый тип `value is ThemeId` — обещание TypeScript'у,
 * что при `true` переданная строка сужается до ThemeId. Без такой проверки
 * значение из cookie (то есть от пользователя, то есть недоверенное) нельзя
 * было бы использовать как ThemeId.
 */
export function isThemeId(value: unknown): value is ThemeId {
  return typeof value === "string" && THEMES.some((theme) => theme.id === value);
}

/**
 * Приводит любое значение к корректному идентификатору темы.
 * Если пришло что-то неизвестное (испорченная cookie, старая версия сайта) —
 * молча возвращаем тему по умолчанию. Приложение не должно падать из-за
 * мусора в cookie.
 */
export function resolveThemeId(value: unknown): ThemeId {
  return isThemeId(value) ? value : DEFAULT_THEME;
}

/** Находит описание темы по идентификатору (для подписи и превью). */
export function getThemeDefinition(id: ThemeId): ThemeDefinition {
  return THEMES.find((theme) => theme.id === id) ?? THEMES[0];
}
