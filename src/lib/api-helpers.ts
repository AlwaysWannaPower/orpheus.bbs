// ============================================================================
// src/lib/api-helpers.ts — ОБЩИЕ ХЕЛПЕРЫ ДЛЯ ROUTE HANDLERS.
// ----------------------------------------------------------------------------
// Route Handler в Next.js — это просто функция, которая получает Request
// и возвращает Response (стандартные веб-API, такие же как в браузере).
//
// Проблема: в каждом обработчике приходится повторять одно и то же —
// обернуть тело в try/catch, выбрать код ответа, сериализовать JSON.
// Такое дублирование называют «бойлерплейтом» (boilerplate).
//
// Поэтому мы делаем маленькие функции-обёртки, которые берут рутину на себя.
// ============================================================================

/**
 * Успешный JSON-ответ.
 *
 * Response.json(...) — статический метод, который:
 *   1. превращает объект в строку через JSON.stringify;
 *   2. сам ставит заголовок Content-Type: application/json.
 *
 * Дополнительные заголовки можно передать вторым аргументом — например,
 * чтобы запретить кэширование ответа (см. noStoreHeaders).
 */
export function json<T>(data: T, init?: ResponseInit): Response {
  return Response.json(data, init);
}

/**
 * Ошибка в формате JSON: {"error": "текст"}.
 *
 * Почему всегда объект, а не просто текст? Потому что клиенту удобнее
 * разбирать единый формат: он всегда знает, что сообщение лежит в поле error.
 */
export function jsonError(message: string, status: number): Response {
  return Response.json({ error: message }, { status });
}

/**
 * Превращает исключение в аккуратный JSON-ответ.
 *
 * ── ЗАЧЕМ ЭТО НУЖНО ───────────────────────────────────────────────────────
 * Без такой обработки необработанная ошибка в Route Handler даёт стандартную
 * страницу ошибки Next.js — некрасивую и бесполезную для клиента, который
 * ждёт JSON. Хелпер гарантирует, что API всегда отвечает понятным JSON.
 *
 * ── ПОЧЕМУ НЕ ФУНКЦИЯ-ОБЁРТКА ─────────────────────────────────────────────
 * Можно было бы написать `export const GET = withErrorHandling(async () => …)`
 * и не повторять try/catch в каждом файле. Но Next.js анализирует экспорты
 * Route Handler и ожидает обычную функцию. Поэтому мы используем самый
 * предсказуемый вариант: явный try/catch и вызов этого хелпера в блоке catch.
 *
 * ── ПРО КОДЫ ОТВЕТА ───────────────────────────────────────────────────────
 * Мы смотрим на текст ошибки и выбираем код. Это компромисс: правильнее было
 * бы завести свой класс ошибки (class NotFoundError extends Error), но для
 * учебного проекта такого правила достаточно, а кода меньше.
 *   * «не найдено»  → 404 Not Found
 *   * «недопустимо» → 400 Bad Request
 *   * остальное     → 500 Internal Server Error
 */
export function handleApiError(error: unknown): Response {
  const message = error instanceof Error ? error.message : "Неизвестная ошибка сервера";

  // console.error печатает полную ошибку со стеком — это для разработчика.
  console.error("[api] ошибка:", error);

  // А клиенту отдаём только сообщение: стек может содержать пути файлов
  // и внутренние детали, которые наружу показывать не нужно.
  if (/не найдено|не найден/i.test(message)) return jsonError(message, 404);
  if (/не указан|недопустим|некорректн/i.test(message)) return jsonError(message, 400);

  return jsonError(message, 500);
}

/**
 * Заголовки «не кэшировать».
 *
 * ── ЗАЧЕМ ─────────────────────────────────────────────────────────────────
 * Браузер и промежуточные прокси любят кэшировать ответы GET. Для списка
 * треков это опасно: пользователь только что переключил «избранное»,
 * а браузер подсовывает старую копию ответа.
 *
 *   no-store            — вообще не сохранять ответ нигде;
 *   must-revalidate     — обязан перепроверять у сервера;
 *   max-age=0           — считать ответ устаревшим немедленно.
 *
 * Для аудиофайлов мы, наоборот, кэш ВКЛЮЧАЕМ — они большие и не меняются.
 */
export const noStoreHeaders: Record<string, string> = {
  "Cache-Control": "no-store, must-revalidate, max-age=0",
};

/**
 * Безопасно достаёт числовой параметр из URL.
 *
 * ── ЗАЧЕМ ─────────────────────────────────────────────────────────────────
 * Всё, что приходит из URL, — это СТРОКИ. И приходит оно от пользователя,
 * то есть ему нельзя доверять. `?limit=abc` не должен ломать сервер.
 *
 * @param value        сырое значение из searchParams (string | null)
 * @param fallback     что вернуть, если значение не число
 * @param min/max      границы, чтобы `?limit=99999999` не съел всю память
 */
export function parseNumberParam(value: string | null, fallback: number, min = 0, max = Number.MAX_SAFE_INTEGER): number {
  if (value === null) return fallback;

  // Number("") === 0, а Number("abc") === NaN. Проверяем оба случая.
  const parsed = Number(value);
  if (!Number.isFinite(parsed)) return fallback;

  // Math.min/Math.max «зажимают» значение в допустимый диапазон.
  return Math.min(Math.max(Math.trunc(parsed), min), max);
}

/**
 * Читает JSON из тела запроса безопасно.
 *
 * Если клиент прислал битый JSON, request.json() бросит исключение.
 * Мы возвращаем null и позволяем обработчику решить, что делать.
 *
 * Дженерик <T> позволяет указать ожидаемую форму:
 *     const body = await readJsonBody<{ name: string }>(request);
 */
export async function readJsonBody<T>(request: Request): Promise<T | null> {
  try {
    return (await request.json()) as T;
  } catch {
    return null;
  }
}
