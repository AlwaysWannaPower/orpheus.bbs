// ── ЗАЧЕМ ВЫНОСИТЬ НАЗВАНИЕ В ОТДЕЛЬНЫЙ ФАЙЛ ──────────────────────────────
// Название встречается в десятке мест: в шапке, в метаданных страницы,
// в README, в имени пользователя Media Session, в логе сервера. Если писать
// строку "ORPHEUS.BBS" руками в каждом месте, то при переименовании
// обязательно что-нибудь забудешь — и в интерфейсе останется старое имя.
//
// Поэтому имя живёт ровно в одном месте, а все остальные файлы импортируют
// его отсюда. Это общий принцип: **любое значение, которое может измениться,
// должно быть объявлено один раз**.
//
// ── ОТКУДА ВЗЯЛОСЬ ИМЯ ────────────────────────────────────────────────────
// Задача была: гибрид древнегреческой культуры и хакерской культуры 90-х.
//
//   ΟΡΦΕΥΣ (Орфей) — мифический музыкант, чья игра укрощала зверей, деревья
//   и даже подземных богов. Для музыкального плеера — идеальный покровитель.
//   Плюс Орфей спускался в подземный мир за Эвридикой: в хакерской культуре
//   это читается как «работа на нижнем уровне системы».
//
//   .BBS — Bulletin Board System: электронные доски объявлений, на которых
//   держалась вся досетевая хакерская культура конца 80-х и 90-х (та самая,
//   из которой вырос фильм «Хакеры» 1995 года). Через BBS распространялись
//   файлы, варез, фанзины и первые вирусы; именно там появился сленг,
//   который мы теперь считаем «хакерским».
//
// Греческий корень даёт миф и музыку, домен BBS — эпоху и технику.
// ============================================================================

