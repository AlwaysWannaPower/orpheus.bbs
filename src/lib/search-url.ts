// ----------------------------------------------------------------------------
// ── ЗАЧЕМ ЭТОТ ФАЙЛ СУЩЕСТВУЕТ ────────────────────────────────────────────
// Логика «превратить текст в адрес» была внутри компонента SearchBar —
// прямо в useEffect. Работало, но у этого было две проблемы:
//
//   1. Логику было НЕЛЬЗЯ ПРОТЕСТИРОВАТЬ. Чтобы проверить, что происходит
//      при пустом вводе или при неизменившемся адресе, пришлось бы поднимать
//      браузер, React и роутер.
//
//   2. Именно там прятался БЕСКОНЕЧНЫЙ ЦИКЛ запросов (разбор — в
//      SearchBar.tsx). Найти его чтением кода в перемешанных хуках сложнее,
//      чем в отдельной функции на двадцать строк.
//
// Общий принцип: **бизнес-логика должна быть чистой функцией** — то есть
// такой, которая зависит только от аргументов и не трогает ничего снаружи
// (ни DOM, ни сеть, ни состояние React).
//
// Плюсы чистоты:
//   * легко тестируется (см. search-url.test.ts);
//   * её можно переиспользовать в другом месте;
//   * её можно читать с любого места, не разбираясь в React.
// ============================================================================

/**
 * Строит новый адрес страницы с учётом поискового запроса.
 *
 * ── ЧТО ВАЖНО В ПОВЕДЕНИИ ─────────────────────────────────────────────────
 *   * прочие параметры (sort, favorites) НЕ теряются;
 *   * пустой запрос убирает параметр search из адреса целиком,
 *     чтобы адрес оставался чистым: "/" вместо "/?search=";
 *   * пробелы по краям обрезаются: «  атл  » и «атл» — одно и то же.
 *
 * ── ГЛАВНОЕ: ФУНКЦИЯ ВОЗВРАЩАЕТ null, ЕСЛИ НИЧЕГО НЕ МЕНЯЕТСЯ ────────────
 * Это ключевое решение, и именно оно защищает от бесконечного цикла.
 *
 * Сравни два подхода:
 *
 *   ❌ «всегда возвращаем адрес» — компонент вызывает router.replace,
 *      адрес «меняется» на такой же, роутер делает запрос на сервер,
 *      компонент перерисовывается, эффект запускается заново…
 *
 *   ✅ «возвращаем null, если менять нечего» — компонент просто выходит,
 *      запроса нет, цикла нет.
 *
 * Возвращать «ничего не делать» отдельным значением — простой и надёжный
 * приём. Он делает функцию ИДЕМПОТЕНТНОЙ: сколько раз её ни применяй
 * к уже готовому адресу, она больше ничего не изменит. Именно это свойство
 * и проверяется в тесте ниже.
 *
 * @param currentParams текущие параметры адреса (обычно из useSearchParams)
 * @param pathname      путь страницы, например "/" или "/playlists/3"
 * @param rawValue      то, что ввёл пользователь (может содержать пробелы)
 * @returns новый адрес — либо null, если адрес уже правильный
 */
export function buildSearchUrl(
  currentParams: URLSearchParams,
  pathname: string,
  rawValue: string,
): string | null {
  const value = rawValue.trim();
  const currentValue = currentParams.get("search") ?? "";

  // --------------------------------------------------------------------------
  // ПЕРВЫЙ ПРЕДОХРАНИТЕЛЬ: уже всё правильно — выходим.
  //
  // Без этой проверки получится цикл: эффект меняет адрес → адрес меняет
  // зависимость эффекта → эффект запускается снова → и так до перезагрузки.
  // --------------------------------------------------------------------------
  if (value === currentValue) return null;

  // Копируем параметры, чтобы не мутировать переданный объект.
  // Мутация чужих данных — источник самых неприятных багов: «я поменял
  // параметры, а сломалась совсем другая часть интерфейса».
  const params = new URLSearchParams(currentParams.toString());

  if (value === "") {
    // Убираем параметр совсем: "/" чище, чем "/?search=".
    params.delete("search");
  } else {
    params.set("search", value);
  }

  const query = params.toString();
  const nextUrl = query ? `${pathname}?${query}` : pathname;

  // --------------------------------------------------------------------------
  // ВТОРОЙ ПРЕДОХРАНИТЕЛЬ: адрес получился ТАКОЙ ЖЕ, как был.
  //
  // Такое возможно, например, когда в адресе был "?search=атл&search=атл"
  // или когда браузер нормализует запись. Проверяем ещё раз — по факту.
  // --------------------------------------------------------------------------
  const currentUrl = currentParams.toString() ? `${pathname}?${currentParams.toString()}` : pathname;
  if (nextUrl === currentUrl) return null;

  return nextUrl;
}
