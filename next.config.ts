// ============================================================================
// next.config.ts — главный конфигурационный файл Next.js.
// ----------------------------------------------------------------------------
// Next.js читает этот файл при СТАРТЕ (dev/build/start), а не в браузере.
// Всё, что здесь написано, влияет на то, как Next собирает и запускает проект.
// Тип NextConfig даёт автодополнение и проверку опечаток в редакторе.
// ============================================================================

import type { NextConfig } from "next";

const nextConfig: NextConfig = {
  // --------------------------------------------------------------------------
  // 1. React Compiler
  // --------------------------------------------------------------------------
  // Компилятор React сам расставляет useMemo / useCallback / React.memo там,
  // где это реально нужно. Благодаря этому нам НЕ надо вручную оборачивать
  // каждую функцию в useCallback — код остаётся читаемым, а лишних
  // перерисовок не появляется.
  //
  // Практическое следствие для нас: пишем «наивный» React-код, компилятор
  // позаботится об оптимизации. Но правила хуков соблюдать всё равно строго:
  // компилятор НЕ прощает мутацию значений во время рендера.
  reactCompiler: true,

  // --------------------------------------------------------------------------
  // 2. Про serverExternalPackages (проверено на практике)
  // --------------------------------------------------------------------------
  // В Next.js есть опция serverExternalPackages, которая говорит «не
  // запаковывай этот пакет в сборку, оставь его отдельным модулем».
  //
  // Мы её ПРОБОВАЛИ для music-metadata и получили ошибку времени выполнения:
  //     Cannot find package 'music-metadata-...'
  // Turbopack в этом режиме подменяет имя пакета на хэшированный псевдоним,
  // который затем не может найти. Без этой опции (то есть при обычной
  // упаковке) music-metadata работает корректно — проверено на реальных mp3.
  //
  // Поэтому опция закомментирована. Если однажды пакет начнёт падать —
  // вот она, под рукой:
  //
  //   serverExternalPackages: ["music-metadata"],
  //
  // Мораль: конфигурация из документации не всегда подходит именно твоей
  // версии фреймворка. Проверяй руками, а не верь на слово.

  // --------------------------------------------------------------------------
  // 3. Заголовки безопасности и кэширования ответов
  // --------------------------------------------------------------------------
  // headers() возвращает массив правил: для каких путей какие HTTP-заголовки
  // добавить. Это обычные HTTP-заголовки — браузер получит их вместе с ответом.
  async headers() {
    return [
      {
        // source — шаблон пути. :path* означает «любой вложенный путь».
        source: "/api/:path*",
        headers: [
          // Запрещаем браузеру «угадывать» тип файла — защита от подмены MIME.
          { key: "X-Content-Type-Options", value: "nosniff" },
        ],
      },
    ];
  },
};

export default nextConfig;
