// src/app/playlists/[id]/not-found.tsx — «ПЛЕЙЛИСТ НЕ НАЙДЕН».
// ----------------------------------------------------------------------------
// Локальная страница 404 для раздела плейлистов.
//
// ── ЗАЧЕМ ЛОКАЛЬНАЯ, ЕСЛИ ЕСТЬ ОБЩАЯ ──────────────────────────────────────
// Файл not-found.tsx можно положить в любую папку маршрута. Next.js возьмёт
// БЛИЖАЙШИЙ к месту ошибки: сначала ищет в текущем сегменте, потом поднимается
// выше, и только в самом конце использует корневой.
//
// Зачем это нужно: в контексте плейлиста можно сказать конкретнее —
// «плейлист удалён или ссылка неверна», а не абстрактное «страница не найдена».
// Пользователю это помогает понять, что произошло.
//
// ── ВАЖНЫЙ УРОК ПРО КОД ОТВЕТА (проверено на практике) ───────────────────
// Изначально в проекте был корневой `src/app/loading.tsx`. Он создавал
// границу <Suspense> прямо под корневым layout, из-за чего оболочка страницы
// начинала отправляться браузеру ДО того, как страница вызовет notFound().
//
// В HTTP статус-код отправляется в первом же байте ответа. Если ответ уже
// начал «течь» (streaming), поменять 200 на 404 технически невозможно.
// В результате отсутствующий плейлист отдавался с кодом 200 — а это неверно:
// и поисковые роботы, и curl, и любые программы должны видеть настоящий 404.
//
// Поэтому мы убрали корневой loading.tsx. Плата — нет экрана загрузки.
// Выгода — честные коды ответа. Для локального приложения, где запрос
// к SQLite занимает около миллисекунды, экран загрузки всё равно никогда
// не успевал показаться, так что потеря нулевая.
//
// Мораль: удобство интерфейса иногда конфликтует с корректностью протокола.
// Выбирай корректность, когда речь о контракте с внешним миром.
// ============================================================================

