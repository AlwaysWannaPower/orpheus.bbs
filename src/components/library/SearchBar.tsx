"use client";

// ============================================================================
// src/components/library/SearchBar.tsx — ПОИСК ПО БИБЛИОТЕКЕ.
// ----------------------------------------------------------------------------
// ── ГЛАВНАЯ ИДЕЯ: СОСТОЯНИЕ ПОИСКА ЖИВЁТ В URL, А НЕ В REACT ──────────────
//
// Соблазнительно сделать так:
//     const [query, setQuery] = useState("");
//     ...фильтровать массив треков прямо в браузере.
//
// Мы так НЕ делаем, и вот почему:
//
//   1. МАСШТАБ. В библиотеке может быть 5000 треков. Фильтровать их в
//      браузере — значит держать все 5000 объектов в памяти и перебирать
//      их на каждое нажатие клавиши.
//
//   2. ПРАВИЛЬНОЕ МЕСТО ДЛЯ ПОИСКА — БАЗА. SQLite делает это за миллисекунды,
//      и в браузер уезжает только результат.
//
//   3. ССЫЛКА СТАНОВИТСЯ РАБОЧЕЙ. Поиск «?search=атл» можно скопировать
//      и отправить другу, добавить в закладки, вернуться кнопкой «назад».
//      С локальным состоянием это невозможно.
//
//   4. ПЕРЕЗАГРУЗКА НЕ ТЕРЯЕТ РЕЗУЛЬТАТ. F5 — и поиск на месте.
//
// Этот приём называется «URL как состояние» (URL as state) и является
// одним из главных идиомов Next.js.
//
// ── ⚠ РАЗБОР РЕАЛЬНОГО БАГА, КОТОРЫЙ ЗДЕСЬ БЫЛ ───────────────────────────
//
// Однажды в консоли сервера появилось вот это, раз в секунду и бесконечно:
//
//     GET /?search=%D1%8F%D1%89%D0%B8%D0%BA 200 in 18ms
//     GET /?search=%D1%8F%D1%89%D0%B8%D0%BA 200 in 19ms
//     GET /?search=%D1%8F%D1%89%D0%B8%D0%BA 200 in 24ms
//     ...
//
// Причина — одна строка в списке зависимостей useEffect: `searchParams`.
//
// Что происходило по шагам:
//   1. Пользователь ввёл текст → сработал дебаунс → router.replace(новый URL)
//   2. URL изменился → ХУК useSearchParams вернул НОВЫЙ объект
//   3. Новый объект — это изменившаяся зависимость → эффект запустился заново
//   4. Эффект снова поставил таймер и снова вызвал router.replace
//   5. …и так по кругу, вечно, с частотой «дебаунс + время запроса»
//
// Обрати внимание на коварство: URL на каждом круге был ОДИН И ТОТ ЖЕ.
// Мы просили сервер отрисовать ровно ту же страницу — но просили
// бесконечно. Внешне интерфейс выглядел нормально, а сервер работал вхолостую.
//
// ── КАК ЭТО ИСПРАВЛЕНО ────────────────────────────────────────────────────
//
// Два независимых предохранителя:
//
//   A. ГЛАВНЫЙ: если значение в поле уже совпадает с тем, что в URL —
//      выходим из эффекта и НИЧЕГО не делаем. Именно это разрывает цикл.
//
//   B. `searchParams` убран из зависимостей; вместо него читается значение
//      `urlSearch` (обычная строка) — строки сравниваются по значению, а не
//      по ссылке, поэтому ложных срабатываний нет.
//
// Плюс третий предохранитель — ref `lastWrittenRef`, который помогает
// отличить «пользователь печатает» от «URL изменился извне» (например,
// сработала ссылка «сбросить»).
//
// ── УРОК НА БУДУЩЕЕ ───────────────────────────────────────────────────────
// Если эффект изменяет значение, от которого сам же зависит, — это почти
// всегда бесконечный цикл. Лечится одним из двух:
//   * убрать зависимость (читать актуальное значение из ref);
//   * поставить guard: «если менять нечего — ничего не делай».
// Второй вариант надёжнее, и здесь применены оба.
// ============================================================================

import { useEffect, useRef, useState } from "react";
import { usePathname, useRouter, useSearchParams } from "next/navigation";

import { buildSearchUrl } from "@/lib/search-url";

/** Через сколько миллисекунд после последнего нажатия обновлять URL. */
const DEBOUNCE_MS = 300;

export function SearchBar() {
  const router = useRouter();
  const pathname = usePathname();
  const searchParams = useSearchParams();

  // --------------------------------------------------------------------------
  // Извлекаем ЗНАЧЕНИЕ, а не объект.
  //
  // `searchParams.get(...)` возвращает строку или null. Строка сравнивается
  // по значению: "ящик" === "ящик" → true. А вот объект searchParams при
  // каждом изменении URL получает НОВУЮ ссылку, и `obj1 === obj2` даёт false
  // даже при одинаковом содержимом. Именно на этом ловится цикл из истории
  // выше.
  // --------------------------------------------------------------------------
  const urlSearch = searchParams.get("search") ?? "";

  // --------------------------------------------------------------------------
  // ЛОКАЛЬНОЕ СОСТОЯНИЕ ДЛЯ ПОЛЯ ВВОДА.
  //
  // Оно нужно, чтобы буквы появлялись в поле мгновенно, без ожидания
  // круговорота «запрос → сервер → RSC → перерисовка».
  // --------------------------------------------------------------------------
  const [value, setValue] = useState(urlSearch);

  // --------------------------------------------------------------------------
  // ЧТО МЫ ЗАПИСАЛИ В URL ПОСЛЕДНИЙ РАЗ.
  //
  // Нужно, чтобы отличить два разных события:
  //   * пользователь печатает → мы сами поменяли URL → поле трогать не надо;
  //   * URL изменился ИЗВНЕ (нажали «сбросить», перешли по ссылке, нажали
  //     «назад») → надо обновить поле ввода, иначе оно будет показывать
  //     старый запрос, которого в адресе уже нет.
  //
  // Начальное значение — то, что пришло с сервера при первом рендере.
  // --------------------------------------------------------------------------
  const lastWrittenRef = useRef(urlSearch);

  // --------------------------------------------------------------------------
  // СВЕЖАЯ КОПИЯ searchParams В REF.
  //
  // Внутри таймера нам нужны ВСЕ текущие параметры (чтобы не потерять sort
  // и favorites при записи search). Но если положить объект searchParams
  // в зависимости эффекта — вернётся тот самый бесконечный цикл: у объекта
  // новая ссылка при каждом изменении URL.
  //
  // Поэтому держим его в ref, а в зависимостях оставляем только СТРОКУ
  // urlSearch. Ref обновляется после каждого рендера — это не вызывает
  // перерисовок и не может зациклиться.
  //
  // (У эффекта нет списка зависимостей — значит он выполняется после
  //  каждого рендера. Здесь это именно то, что нужно.)
  // --------------------------------------------------------------------------
  const searchParamsRef = useRef(searchParams);
  useEffect(() => {
    searchParamsRef.current = searchParams;
  });

  // --------------------------------------------------------------------------
  // ПРЕДОХРАНИТЕЛЬ 1: СИНХРОНИЗАЦИЯ СВЕРХУ ВНИЗ (URL → поле ввода).
  //
  // Срабатывает только если в URL оказалось что-то, чего мы не писали сами.
  // --------------------------------------------------------------------------
  useEffect(() => {
    if (urlSearch === lastWrittenRef.current) return;

    // URL изменился не нашими руками — подтягиваем значение в поле.
    lastWrittenRef.current = urlSearch;
    setValue(urlSearch);
  }, [urlSearch]);

  // --------------------------------------------------------------------------
  // ПРЕДОХРАНИТЕЛЬ 2: СИНХРОНИЗАЦИЯ СНИЗУ ВВЕРХ (поле ввода → URL), С ДЕБАУНСОМ.
  //
  // Дебаунс («дребезг») нужен, чтобы не отправлять на сервер запрос на каждую
  // букву слова «linkin» — это были бы семь запросов вместо одного.
  //
  // ── КАК РАБОТАЕТ ОЧИСТКА ─────────────────────────────────────────────────
  // useEffect может вернуть функцию очистки. Если `value` изменится раньше,
  // чем пройдут 300 мс, React вызовет очистку предыдущего эффекта — таймер
  // отменится. Срабатывает только ПОСЛЕДНИЙ таймер.
  // --------------------------------------------------------------------------
  useEffect(() => {
    // ------------------------------------------------------------------------
    // ВСЯ ЛОГИКА — В ЧИСТОЙ ФУНКЦИИ buildSearchUrl (см. src/lib/search-url.ts).
    //
    // Она возвращает null, если менять нечего. Это ГЛАВНАЯ защита от
    // бесконечного цикла: без неё эффект менял бы адрес, адрес менял бы
    // зависимость эффекта, и сервер получал бы запрос за запросом вечно.
    //
    // Логика вынесена из компонента не «для красоты»: чистую функцию можно
    // протестировать без браузера и React. Тесты — в
    // src/lib/search-url.test.ts, и один из них проверяет именно
    // идемпотентность (повторное применение ничего не меняет).
    // ------------------------------------------------------------------------
    const nextUrl = buildSearchUrl(searchParamsRef.current, pathname, value);

    // ⚠ ГЛАВНАЯ СТРОКА, КОТОРАЯ ЛЕЧИТ БЕСКОНЕЧНЫЙ ЦИКЛ.
    // Если менять нечего — выходим, не ставя таймер и не дёргая сервер.
    if (nextUrl === null) return;

    const timer = window.setTimeout(() => {
      // Помечаем, что это изменение сделали МЫ, — чтобы предохранитель 1
      // не принял его за внешнее и не перезаписал поле ввода.
      lastWrittenRef.current = value.trim();

      // --------------------------------------------------------------------
      // router.replace вместо router.push.
      //
      // push добавляет новую запись в историю браузера. При поиске это
      // означало бы, что кнопка «назад» отматывает по одной букве —
      // крайне раздражающее поведение.
      //
      // replace заменяет текущую запись: «назад» вернёт туда, где
      // пользователь был до начала поиска. Именно так и надо.
      // --------------------------------------------------------------------
      router.replace(nextUrl, { scroll: false });
    }, DEBOUNCE_MS);

    return () => window.clearTimeout(timer);
    // В зависимостях только СКАЛЯРНЫЕ значения: две строки и стабильные
    // объекты роутера. Никаких searchParams — см. разбор бага в шапке файла.
  }, [value, urlSearch, pathname, router]);

  return (
    <div className="relative min-w-[200px] flex-1">
      {/* Декоративный префикс «как в терминале» */}
      <span className="pointer-events-none absolute left-2 top-1/2 -translate-y-1/2 select-none text-[12px] text-ink-muted">
        &gt;
      </span>

      <input
        type="search"
        className="term-input !pl-5"
        placeholder="поиск: название, исполнитель, альбом…"
        value={value}
        onChange={(event) => setValue(event.target.value)}
        // aria-label обязателен: placeholder НЕ является подписью поля
        // для скринридеров — он исчезает при вводе текста.
        aria-label="Поиск по библиотеке"
        // autoComplete="off" убирает выпадающие подсказки браузера,
        // которые перекрывают список результатов.
        autoComplete="off"
      />

      {value !== "" && (
        <button
          type="button"
          onClick={() => setValue("")}
          className="absolute right-2 top-1/2 -translate-y-1/2 text-[12px] text-ink-muted hover:text-ink"
          aria-label="Очистить поиск"
          title="Очистить"
        >
          ✕
        </button>
      )}
    </div>
  );
}
