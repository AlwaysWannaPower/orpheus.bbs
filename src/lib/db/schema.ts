// ============================================================================
// src/lib/db/schema.ts — ОПИСАНИЕ ТАБЛИЦ БАЗЫ ДАННЫХ.
// ----------------------------------------------------------------------------
// Здесь мы описываем структуру базы НА ЯЗЫКЕ TYPESCRIPT, а не в SQL-файле.
// Drizzle ORM читает это описание и умеет:
//   1. сгенерировать SQL (CREATE TABLE / ALTER TABLE / SELECT ...);
//   2. вывести типы TypeScript для чтения и записи строк.
//
// Именно из-за пункта 2 это и называется «TypeScript-first ORM»: если в коде
// написать track.titel вместо track.title — редактор подчеркнёт ошибку сразу,
// ещё до запуска. В обычном SQL такая опечатка выяснилась бы только в рантайме.
//
// ── ГЛАВНАЯ АНАЛОГИЯ ───────────────────────────────────────────────────────
//   таблица  (table)  =  лист таблицы в Excel
//   колонка  (column) =  столбец этого листа
//   строка   (row)    =  одна запись, например одна песня
// ============================================================================

import { index, integer, primaryKey, real, sqliteTable, text, uniqueIndex } from "drizzle-orm/sqlite-core";

// ============================================================================
// ТАБЛИЦА 1: tracks — картотека всех найденных аудиофайлов.
// ----------------------------------------------------------------------------
// ГЛАВНАЯ ИДЕЯ АРХИТЕКТУРЫ (повторяется в ТЗ):
//     файловая система = источник правды (реальные mp3-файлы на диске)
//     SQLite           = ИНДЕКС этих файлов (быстрый поиск, сортировка, связи)
//
// Файлы — главные. База — производная. Поэтому её всегда можно удалить
// и пересобрать сканером. Это очень удобное свойство: база не может
// «разъехаться» с реальностью навсегда.
// ============================================================================
export const tracks = sqliteTable(
  "tracks",
  {
    // -----------------------------------------------------------------------
    // id — первичный ключ (primary key).
    // Свойство primary key: значение уникально для каждой строки и никогда
    // не бывает NULL. По нему мы ссылаемся на песню из других таблиц.
    //
    // autoIncrement: true — SQLite сам выдаёт 1, 2, 3, ... при вставке.
    // В SQLite это на самом деле псевдоним для типа INTEGER PRIMARY KEY,
    // который ещё называют rowid — самый быстрый способ найти строку.
    // -----------------------------------------------------------------------
    id: integer("id").primaryKey({ autoIncrement: true }),

    // -----------------------------------------------------------------------
    // path — АБСОЛЮТНЫЙ путь к файлу на диске. Например:
    //   /home/august/music/ATL - Ящик.mp3
    //
    // .notNull()  — колонка обязана быть заполнена (в SQL: NOT NULL).
    // uniqueIndex — гарантия уникальности на уровне САМОЙ базы (в SQL:
    //               CREATE UNIQUE INDEX). Даже если в коде случится баг,
    //               база не даст вставить один и тот же файл дважды.
    //
    // Благодаря уникальности мы можем делать "INSERT ... ON CONFLICT(path)
    // DO UPDATE" — то есть upsert: «вставь, а если такой путь уже есть —
    // обнови». Это основа повторного сканирования.
    // -----------------------------------------------------------------------
    path: text("path").notNull(),

    // Имя файла без папок: "ATL - Ящик.mp3". Нужно для быстрого поиска и
    // для запасного варианта заголовка, если в тегах ничего нет.
    filename: text("filename").notNull(),

    // -----------------------------------------------------------------------
    // search_text — «поисковый слепок» строки, всегда в НИЖНЕМ РЕГИСТРЕ.
    //
    // ── Зачем это нужно (важный подводный камень SQLite) ───────────────────
    // В SQLite оператор LIKE регистронезависим ТОЛЬКО для латиницы.
    // Запрос `WHERE title LIKE '%атл%'` не найдёт песню "АТЛ", потому что
    // SQLite понятия не имеет о кириллическом регистре (для этого нужна
    // сборка с ICU, а она есть не везде).
    //
    // Решение: приводим строку к нижнему регистру средствами JavaScript
    // (а JS знает про Unicode отлично) и сохраняем результат в отдельную
    // колонку. При поиске точно так же понижаем регистр у запроса и ищем
    // обычным LIKE уже без всяких преобразований.
    //
    // Это классический приём денормализации: мы сознательно дублируем данные
    // в другом виде, чтобы запрос стал простым и быстрым.
    // -----------------------------------------------------------------------
    searchText: text("search_text").notNull().default(""),

    // -----------------------------------------------------------------------
    // Поля ниже приходят из ТЕГОВ (метаданных внутри файла).
    // У mp3 это ID3v2, у flac — Vorbis Comment, у m4a — iTunes-атомы.
    // music-metadata читает их все и приводит к общему виду.
    //
    // У всех этих полей есть .notNull() и значение по умолчанию при вставке:
    // если тега нет, мы подставляем "Unknown" или 0. Тогда в коде не нужно
    // на каждом шагу проверять `if (track.artist === null)`. Пусть лучше
    // в базе лежит честное "Unknown" — с ним проще жить.
    // -----------------------------------------------------------------------
    title: text("title").notNull(),
    artist: text("artist").notNull(),
    album: text("album").notNull(),
    albumArtist: text("album_artist").notNull(),
    genre: text("genre").notNull(),

    // Год выпуска. Целое число. 0 = «неизвестно».
    year: integer("year").notNull().default(0),

    // Номер трека внутри альбома. Нужен, чтобы альбом игрался в правильном
    // порядке, а не в алфавитном.
    trackNumber: integer("track_number").notNull().default(0),

    // -----------------------------------------------------------------------
    // real — число с плавающей точкой (в SQL: REAL).
    // Длительность трека в СЕКУНДАХ, например 213.457.
    // Дробное значение нужно потому, что mp3-фреймы длятся не ровно секунду.
    // -----------------------------------------------------------------------
    duration: real("duration").notNull().default(0),

    // Размер файла в байтах. Вместе с mtime используется для проверки
    // «изменился ли файл с прошлого сканирования».
    size: integer("size").notNull().default(0),

    // -----------------------------------------------------------------------
    // mtime — время последнего изменения файла на диске.
    // mode: "timestamp_ms" означает: в SQLite лежит целое число
    // (миллисекунды с 1 января 1970 года, UTC), а Drizzle автоматически
    // превращает его в обычный JS-объект Date при чтении и обратно при записи.
    //
    // Тут мы храним НЕ наше время, а время файловой системы — это «отпечаток»
    // файла. Если пользователь перекодирует mp3, mtime изменится, и сканер
    // поймёт, что надо перечитать теги.
    // -----------------------------------------------------------------------
    mtime: integer("mtime", { mode: "timestamp_ms" }).notNull(),

    // -----------------------------------------------------------------------
    // isFavorite: 0 или 1.
    //
    // В SQLite НЕТ отдельного булева типа — есть только целые числа, строки,
    // числа с точкой, blob и NULL. Поэтому boolean хранят как 0/1.
    // Drizzle умеет прятать это безобразие: mode: "boolean" превращает
    // колонку в настоящий true/false в TypeScript.
    // -----------------------------------------------------------------------
    isFavorite: integer("is_favorite", { mode: "boolean" }).notNull().default(false),

    // Имя файла с обложкой внутри COVERS_DIR (например "12.jpg") либо null.
    coverFile: text("cover_file"),

    // Когда запись появилась в базе и когда последний раз обновлялась.
    // $defaultFn — функция JS, которая вызывается при вставке. Удобно, что
    // не надо руками проставлять дату в каждом месте кода.
    createdAt: integer("created_at", { mode: "timestamp_ms" })
      .notNull()
      .$defaultFn(() => new Date()),

    updatedAt: integer("updated_at", { mode: "timestamp_ms" })
      .notNull()
      .$defaultFn(() => new Date()),
  },
  // -------------------------------------------------------------------------
  // Второй аргумент sqliteTable — настройки таблицы: индексы и ограничения.
  // В новых версиях Drizzle это ФУНКЦИЯ, возвращающая МАССИВ (раньше
  // возвращала объект — старые примеры в интернете выглядят иначе).
  //
  // Что такое индекс простыми словами: это как алфавитный указатель в конце
  // книги. Без него, чтобы найти песню по исполнителю, база честно прочитает
  // ВСЕ 10 000 строк. С индексом — прыгнет сразу в нужное место.
  //
  // Плата за индекс: он занимает место и чуть-чуть замедляет вставку.
  // Поэтому индексы делают только там, где реально ищут/сортируют.
  // -------------------------------------------------------------------------
  (table) => [
    // Путь обязан быть уникальным — это ключ для upsert при сканировании.
    uniqueIndex("tracks_path_unique").on(table.path),
    // Мы часто фильтруем и группируем по этим полям — индексируем.
    index("tracks_artist_idx").on(table.artist),
    index("tracks_album_idx").on(table.album),
    index("tracks_created_idx").on(table.createdAt),
  ],
);

// ============================================================================
// ТАБЛИЦА 2: playlists — пользовательские плейлисты.
// ----------------------------------------------------------------------------
// Обрати внимание: плейлисты НЕ хранят музыку. Они хранят только название,
// а список песен живёт в отдельной таблице playlist_tracks (см. ниже).
// Такое разделение называется нормализацией: одни данные — в одном месте.
// ============================================================================
export const playlists = sqliteTable("playlists", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  name: text("name").notNull(),
  // Необязательное описание — знак вопроса у типа в TS будет string | null.
  description: text("description"),
  createdAt: integer("created_at", { mode: "timestamp_ms" })
    .notNull()
    .$defaultFn(() => new Date()),
});

// ============================================================================
// ТАБЛИЦА 3: playlist_tracks — СВЯЗУЮЩАЯ таблица (many-to-many).
// ----------------------------------------------------------------------------
// Отношение «многие-ко-многим»: один плейлист содержит много треков,
// один трек может лежать в нескольких плейлистах.
//
// В реляционной базе такое отношение ВСЕГДА выражается третьей таблицей,
// где каждая строка — это факт «трек X лежит в плейлисте Y на позиции Z».
//
//   playlists          playlist_tracks            tracks
//   ┌────┐             ┌───────────────┐          ┌────┐
//   │ id │◄────────────│ playlist_id   │          │ id │
//   │name│             │ track_id      │─────────►│title│
//   └────┘             │ position      │          └────┘
//                      └───────────────┘
// ============================================================================
export const playlistTracks = sqliteTable(
  "playlist_tracks",
  {
    // -----------------------------------------------------------------------
    // references() — это ВНЕШНИЙ КЛЮЧ (foreign key).
    // Он говорит базе: «playlist_id обязан существовать в таблице playlists».
    // Если попытаться добавить трек в несуществующий плейлист, база откажет.
    //
    // onDelete: "cascade" — каскадное удаление: удалили плейлист → все строки
    // про его треки удалились сами. Без этого в базе остались бы «сироты».
    //
    // ВАЖНО: SQLite по умолчанию НЕ проверяет внешние ключи! Их надо явно
    // включить командой `PRAGMA foreign_keys = ON` — мы делаем это при
    // открытии соединения (см. src/lib/db/client.ts).
    // -----------------------------------------------------------------------
    playlistId: integer("playlist_id")
      .notNull()
      .references(() => playlists.id, { onDelete: "cascade" }),
    trackId: integer("track_id")
      .notNull()
      .references(() => tracks.id, { onDelete: "cascade" }),

    // Порядковый номер внутри плейлиста. Именно по нему сортируется вывод.
    // Хранить порядок числом (а не полагаться на id) важно: пользователь
    // может перетащить трек наверх, и порядок изменится, а id — нет.
    position: integer("position").notNull().default(0),

    addedAt: integer("added_at", { mode: "timestamp_ms" })
      .notNull()
      .$defaultFn(() => new Date()),
  },
  (table) => [
    // -----------------------------------------------------------------------
    // СОСТАВНОЙ (композитный) первичный ключ из двух колонок.
    // Смысл: одна и та же пара (плейлист, трек) может встречаться только
    // один раз — нельзя положить песню в плейлист дважды.
    //
    // Но обрати внимание: (1, 5) и (2, 5) — разные пары, поэтому один трек
    // спокойно лежит в разных плейлистах.
    // -----------------------------------------------------------------------
    primaryKey({ columns: [table.playlistId, table.trackId] }),
    index("playlist_tracks_position_idx").on(table.playlistId, table.position),
  ],
);

// ============================================================================
// ТАБЛИЦА 4: play_history — история прослушиваний.
// ----------------------------------------------------------------------------
// Это журнал событий (event log): каждая строка = «в момент времени T
// пользователь включил трек X».
//
// ── СВЯЗЬ С ТВОИМ ОСНОВНЫМ КУРСОМ (ClickHouse / dbt / BI) ──────────────────
// Именно так устроены таблицы фактов (fact tables) в аналитике.
// Если бы мы делали аналитику по прослушиваниям, эта таблица была бы
// источником для dbt-модели:
//     stg_play_history → fct_listens → витрина «топ исполнителей за месяц»
// Разница только в объёме: у нас сотни строк, в ClickHouse — миллиарды.
// ============================================================================
export const playHistory = sqliteTable(
  "play_history",
  {
    id: integer("id").primaryKey({ autoIncrement: true }),
    trackId: integer("track_id")
      .notNull()
      .references(() => tracks.id, { onDelete: "cascade" }),
    playedAt: integer("played_at", { mode: "timestamp_ms" })
      .notNull()
      .$defaultFn(() => new Date()),
  },
  (table) => [
    // Индекс по убыванию даты — нам почти всегда нужны последние события.
    index("play_history_played_at_idx").on(table.playedAt),
  ],
);

// ============================================================================
// ТАБЛИЦА 5: playback_state — «одна строка на весь плеер».
// ----------------------------------------------------------------------------
// Хранит, на каком месте пользователь остановился, чтобы при следующем
// открытии сайта можно было предложить «Продолжить слушать».
//
// Мы жёстко фиксируем id = 1 (в коде всегда пишем ON CONFLICT(id) DO UPDATE).
// Такой приём называют singleton-таблицей: настроек ровно один комплект,
// и пользователей у приложения тоже один — сам хозяин.
// ============================================================================
export const playbackState = sqliteTable("playback_state", {
  id: integer("id").primaryKey(),
  trackId: integer("track_id").references(() => tracks.id, { onDelete: "set null" }),
  // Позиция внутри трека в секундах, например 73.42.
  position: real("position").notNull().default(0),
  updatedAt: integer("updated_at", { mode: "timestamp_ms" })
    .notNull()
    .$defaultFn(() => new Date()),
});

// ============================================================================
// ТИПЫ, ВЫВЕДЕННЫЕ ИЗ СХЕМЫ.
// ----------------------------------------------------------------------------
// Это одна из самых приятных возможностей Drizzle: не надо вручную писать
// interface Track { id: number; path: string; ... } и потом следить, чтобы он
// не разошёлся со схемой. TypeScript выведет типы сам, а если ты добавишь
// колонку в схему — тип обновится автоматически.
//
//   $inferSelect — форма строки, которую база ВОЗВРАЩАЕТ (всё заполнено).
//   $inferInsert — форма объекта для ВСТАВКИ (поля с default можно не указывать).
//
// `export type X = typeof table.$inferSelect` — читается как:
//   «возьми значение table.$inferSelect и узнай его тип».
// ============================================================================

/** Строка таблицы tracks, как её возвращает SELECT. */
export type TrackRow = typeof tracks.$inferSelect;

/** Объект для вставки в tracks (id и даты можно не указывать). */
export type NewTrack = typeof tracks.$inferInsert;

/** Строка таблицы playlists. */
export type PlaylistRow = typeof playlists.$inferSelect;

/** Строка таблицы play_history. */
export type PlayHistoryRow = typeof playHistory.$inferSelect;

/** Строка таблицы playback_state. */
export type PlaybackStateRow = typeof playbackState.$inferSelect;
